// Command generate produces cohere's ECMAScript Unicode property tables.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"slices"

	"github.com/system-inc/cohere/unicodeproperties/internal/ucd"
)

func main() {
	inventory := flag.Bool("inventory", false, "write inventory JSON to stdout")
	check := flag.Bool("check", false, "check generated tables for freshness")
	output := flag.String("output", "tables_generated.go", "output file")
	flag.Parse()
	tables, buildError := ucd.Build()
	if buildError != nil {
		panic(buildError)
	}
	if *inventory {
		if encodeError := json.NewEncoder(os.Stdout).Encode(tables); encodeError != nil {
			panic(encodeError)
		}
		return
	}
	var buffer bytes.Buffer
	fmt.Fprintln(&buffer, "// Code generated by go generate; DO NOT EDIT.\npackage unicodeproperties")
	fmt.Fprintf(&buffer, "const Version = %q\n", ucd.Version)
	keys := make([]string, 0, len(tables.Properties))
	for key := range tables.Properties {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	fmt.Fprintln(&buffer, "var properties = map[string]Property{")
	for _, key := range keys {
		property := tables.Properties[key]
		fmt.Fprintf(&buffer, "%q: {Family:%q, Ranges: []Range{", key, property.Family)
		for _, span := range property.Ranges {
			fmt.Fprintf(&buffer, "{0x%x,0x%x},", span.Lo, span.Hi)
		}
		fmt.Fprintln(&buffer, "}},")
	}
	fmt.Fprintln(&buffer, "}")
	keys = keys[:0]
	for key := range tables.Aliases {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	fmt.Fprintln(&buffer, "var aliases = map[string]string{")
	for _, key := range keys {
		fmt.Fprintf(&buffer, "%q:%q,\n", key, tables.Aliases[key])
	}
	fmt.Fprintln(&buffer, "}")
	data, formatError := format.Source(buffer.Bytes())
	if formatError != nil {
		panic(formatError)
	}
	if *check {
		old, readError := os.ReadFile(*output)
		if readError != nil {
			panic(readError)
		}
		if !bytes.Equal(old, data) {
			fmt.Fprintln(os.Stderr, "Unicode property tables are stale; run go generate ./unicodeproperties")
			os.Exit(1)
		}
		return
	}
	if writeError := os.WriteFile(*output, data, 0644); writeError != nil {
		panic(writeError)
	}
}
