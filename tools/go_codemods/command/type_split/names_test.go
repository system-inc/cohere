func TestExactCases(test *testing.T) {
	test.Parallel()
	for _, exact := range exactCases {
		test.Run(exact.name, func(test *testing.T) {
			test.Parallel()
			after, result := splitFiles(test, exact.before, exact.pinned)
			for _, name := range slices.Sorted(maps.Keys(after)) {
				if want, expected := exact.after[name]; !expected {
					test.Errorf("%s exists, want it absent:\n%s", name, after[name])
				} else if after[name] != want {
					test.Errorf("%s is\n%s\nwant\n%s", name, after[name], want)
				}
			}
			for _, name := range slices.Sorted(maps.Keys(exact.after)) {
				if _, exists := after[name]; !exists {
					test.Errorf("%s is missing; files: %v", name, slices.Sorted(maps.Keys(after)))
				}
			}
			if len(result.nameConflicts) != exact.nameConflicts {
				test.Errorf("name conflicts %q, want %d", result.nameConflicts, exact.nameConflicts)
			}
			if len(result.conflicts) != exact.conflicts {
				test.Errorf("conflicts %q, want %d", result.conflicts, exact.conflicts)
			}
			if exact.moves != nil {
				var moves []string
				for _, move := range result.moves {
					moves = append(moves, move.from+" -> "+move.to)
				}
				if !slices.Equal(moves, exact.moves) {
					test.Errorf("moves\n%s\nwant\n%s", strings.Join(moves, "\n"), strings.Join(exact.moves, "\n"))
				}
			}
			again, second := splitFiles(test, after, exact.pinned)
			if len(second.changes) > 0 {
				test.Errorf("a second run changes %v", slices.Sorted(maps.Keys(second.changes)))
			}
			if !maps.Equal(again, after) {
				test.Error("a second run's files differ from the first's")
			}
		})
	}
}
