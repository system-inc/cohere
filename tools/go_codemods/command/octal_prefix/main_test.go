// fixtureSource holds every shape the rule decides on: legacy octal in a call, a const block, a separator straight
// after the zero, a generic function, an array length and a switch case, which the pass rewrites, and zero, the
// prefixed bases and a decimal, which it leaves alone.
const fixtureSource = `package fixture

import "os"

func writeConfiguration(path string, contents []byte) error {
	return os.WriteFile(path, contents, 0644)
}

const (
	executable  = 0755
	prefixed    = 0o644
	zero        = 0
	zeroZero    = 00
	separated   = 0_644
	hexadecimal = 0x1F
	binary      = 0b101
	decimal     = 1_000
)

func mask[Value ~uint32](value Value) Value {
	return value & 0777
}

var buffer [010]byte

func describe(mode os.FileMode) string {
	switch mode {
	case 0400:
		return "read only"
	}
	return "0644, in a string"
}
`

// fixtureRewritten is fixtureSource with each legacy octal literal prefixed, and nothing else changed.
const fixtureRewritten = `package fixture

import "os"

func writeConfiguration(path string, contents []byte) error {
	return os.WriteFile(path, contents, 0o644)
}

const (
	executable  = 0o755
	prefixed    = 0o644
	zero        = 0
	zeroZero    = 0o0
	separated   = 0o_644
	hexadecimal = 0x1F
	binary      = 0b101
	decimal     = 1_000
)

func mask[Value ~uint32](value Value) Value {
	return value & 0o777
}

var buffer [0o10]byte

func describe(mode os.FileMode) string {
	switch mode {
	case 0o400:
		return "read only"
	}
	return "0644, in a string"
}
`

// untouchedSources are files the pass must leave byte for byte: a generated file and a copy of upstream source, each
// holding legacy octal the rule would flag, and imaginary literals, which are decimal in Go and the rule never judges.
var untouchedSources = map[string]string{
	"generated.go": "// Code generated by fixture. DO NOT EDIT.\n\npackage fixture\n\nconst generatedMode = 0600\n",
	"copied.go": "// cohere:copied example.com/upstream@v1.0.0 copied.go\n// cohere:until never: a fixture.\n\n" +
		"package fixture\n\nconst copiedMode = 0600\n",
	"imaginary.go": "package fixture\n\nconst (\n\timaginaryInteger = 0644i\n\timaginaryFloat   = 07.5i\n)\n",
}

// writeFixture writes a module of fixtureSource and the untouched sources and returns its root, resolved as Load
// resolves it, so the report's paths read relative to it.
func writeFixture(test *testing.T) string {
	test.Helper()
	root, resolveError := filepath.EvalSymlinks(test.TempDir())
	if resolveError != nil {
		test.Fatal(resolveError)
	}
	files := map[string]string{
		"go.work":    "go 1.27\n\nuse .\n",
		"go.mod":     "module fixture\n\ngo 1.27\n",
		"fixture.go": fixtureSource,
	}
	for name, contents := range untouchedSources {
		files[name] = contents
	}
	for name, contents := range files {
		if writeError := os.WriteFile(filepath.Join(root, name), []byte(contents), 0o644); writeError != nil {
			test.Fatal(writeError)
		}
	}
	return root
}

// readFile is a fixture file's contents.
func readFile(test *testing.T, root string, name string) string {
	test.Helper()
	contents, readError := os.ReadFile(filepath.Join(root, name))
	if readError != nil {
		test.Fatal(readError)
	}
	return string(contents)
}

// requireUntouched fails unless every untouched source holds what was written.
func requireUntouched(test *testing.T, root string) {
	test.Helper()
	for name, contents := range untouchedSources {
		if written := readFile(test, root, name); written != contents {
			test.Errorf("%s reads\n%s\nwant it untouched:\n%s", name, written, contents)
		}
	}
}

// runFixture runs the pass over root and returns its exit code and what it printed.
func runFixture(test *testing.T, root string, dryRun bool) (int, string) {
	test.Helper()
	var output bytes.Buffer
	var errorOutput bytes.Buffer
	exitCode := run(root, nil, dryRun, &output, &errorOutput)
	return exitCode, output.String() + errorOutput.String()
}

// A dry run reports every literal the rule flags and writes nothing. The run rewrites exactly those in editable
// files, proven by the reload, and leaves the generated and copied files, the imaginary literals, zero, the prefixed
// bases and the decimal as written. The rule then reads zero over every file the pass may edit, and a second run
// finds nothing to do and writes nothing.
func TestEveryLegacyOctalIsRewrittenAndNothingElse(test *testing.T) {
	test.Parallel()
	root := writeFixture(test)

	exitCode, printed := runFixture(test, root, true)
	if exitCode != 0 {
		test.Fatalf("the dry run exited %d:\n%s", exitCode, printed)
	}
	for _, want := range []string{
		"candidates: 9 legacy octal literals the rule flags",
		"accepted: 7 literals to rewrite in 1 files",
		"rejected: 2 literals left as written",
		"rejected, a copy of upstream source: 1",
		"rejected, a generated file: 1",
		"rewrite: fixture.go:6:38 0644 -> 0o644",
		"rewrite: fixture.go:14:16 0_644 -> 0o_644",
		"declined: generated.go:5:23 0600: a generated file",
	} {
		if !strings.Contains(printed, want) {
			test.Errorf("the dry run's report holds no %q:\n%s", want, printed)
		}
	}
	if written := readFile(test, root, "fixture.go"); written != fixtureSource {
		test.Fatalf("the dry run wrote fixture.go:\n%s", written)
	}

	exitCode, printed = runFixture(test, root, false)
	if exitCode != 0 || !strings.Contains(printed, "spelled as the rule suggested, 0 mismatches") ||
		!strings.Contains(printed, "wrote 1 files") {
		test.Fatalf("the run exited %d, want the rewrite proven and written:\n%s", exitCode, printed)
	}
	if written := readFile(test, root, "fixture.go"); written != fixtureRewritten {
		test.Fatalf("fixture.go reads\n%s\nwant\n%s", written, fixtureRewritten)
	}
	requireUntouched(test, root)

	loaded, loadError := workspace.Load(root, nil)
	if loadError != nil {
		test.Fatal(loadError)
	}
	for _, analyzedPackage := range loaded.Analyzed {
		diagnostics, findError := findings(analyzedPackage)
		if findError != nil {
			test.Fatal(findError)
		}
		for _, diagnostic := range diagnostics {
			position := analyzedPackage.Fset.Position(diagnostic.Pos)
			if name := filepath.Base(position.Filename); name != "generated.go" && name != "copied.go" {
				test.Errorf("the rule still flags %s: %s", position, diagnostic.Message)
			}
		}
	}

	exitCode, printed = runFixture(test, root, false)
	if exitCode != 0 || !strings.Contains(printed, "accepted: 0 literals") ||
		!strings.Contains(printed, "wrote 0 files, nothing to rewrite") {
		test.Fatalf("a second run exited %d, want nothing to rewrite:\n%s", exitCode, printed)
	}
	if written := readFile(test, root, "fixture.go"); written != fixtureRewritten {
		test.Fatalf("a second run changed fixture.go:\n%s", written)
	}
	requireUntouched(test, root)
}

// A rewrite that keeps every identifier and type-checks but changes a literal's value, 0644 written as 0o645, is a
// mismatch the literal check finds, and nothing is written. The identifiers alone cannot see it.
func TestALiteralWhoseValueChangesWritesNothing(test *testing.T) {
	test.Parallel()
	root := writeFixture(test)
	loaded, loadError := workspace.Load(root, nil)
	if loadError != nil {
		test.Fatal(loadError)
	}
	found, planError := plan(loaded)
	if planError != nil {
		test.Fatal(planError)
	}
	edits, _ := rename.Deduplicate(found.edits)
	changed := 0
	for index := range edits {
		if edits[index].OldText == "0644" {
			edits[index].NewText = "0o645"
			changed++
		}
	}
	if changed != 1 {
		test.Fatalf("want one edit of 0644 to break, found %d", changed)
	}
	var report bytes.Buffer
	var refusals bytes.Buffer
	output := bufio.NewWriter(&report)
	errorOutput := bufio.NewWriter(&refusals)
	exitCode := workspace.ApplyVerifiedChecked(loaded, root, nil, edits, rename.GroupByFile(edits),
		literalCheck(loaded, edits), passName, output, errorOutput)
	if flushError := output.Flush(); flushError != nil {
		test.Fatal(flushError)
	}
	if flushError := errorOutput.Flush(); flushError != nil {
		test.Fatal(flushError)
	}
	printed := report.String() + refusals.String()
	// The type is os.FileMode or io/fs.FileMode, as the toolchain spells the alias, so only its name is held.
	if exitCode != 1 || !strings.Contains(printed, "expected 0o645 (") ||
		!strings.Contains(printed, "FileMode 420), got 0o645 (") || !strings.Contains(printed, "FileMode 421)") ||
		!strings.Contains(printed, "1 mismatches") {
		test.Fatalf("exit %d, want the changed value refused:\n%s", exitCode, printed)
	}
	if written := readFile(test, root, "fixture.go"); written != fixtureSource {
		test.Fatalf("a refused rewrite wrote fixture.go:\n%s", written)
	}
}
