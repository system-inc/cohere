// Command generate_suggestions turns the engine's suggestion recipes into Go.
//
// Usage:
//
//	node internal/lint/rules/tailwind/tools/generate_suggestions/enumerate.mjs --resolve-root ahra: > suggestions.json
//	go run ./internal/lint/rules/tailwind/tools/generate_suggestions -input suggestions.json \
//	    -output internal/lint/rules/tailwind/collapse/framework_suggestions_table.go [-check]
//
// The table is what BuildClassList resolves against a run's theme to rebuild `getClassList()`, the
// population upstream's arbitraryUtilities pass searches (#15swfzq unit 1b). It holds recipes only:
// literal values, namespaces, and the flags for fractions, defaults and the spacing scale. No theme key
// crosses into it, because enumerate.mjs probes a theme of its own making, one key per namespace, and
// records which namespace each key came from rather than the key.
//
// One input rather than several, unlike generate_statics. That tool intersects real design systems
// because a real theme's `@utility` blocks register beside the framework's; the probe theme declares
// none, so what it registers is the framework's alone. Whether the recipes hold on real themes is the
// class-list differential's question, asked on three of them.
//
// -check renders from the input and fails if the file on disk differs, so a Tailwind upgrade that
// changes a recipe is a diff a reviewer reads rather than a class that quietly stops being listed.
//
// Node is required to produce the input and never to use the result.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

type suggestionList struct {
	Literals            []string `json:"literals"`
	SpacingScale        bool     `json:"spacingScale"`
	Namespaces          []string `json:"namespaces"`
	Fractions           bool     `json:"fractions"`
	HasDefault          bool     `json:"hasDefault"`
	DefaultWhenThemeKey string   `json:"defaultWhenThemeKey"`
}

type suggestionGroup struct {
	SupportsNegative bool           `json:"supportsNegative"`
	Values           suggestionList `json:"values"`
	Modifiers        suggestionList `json:"modifiers"`
}

type suggestionsFile struct {
	TailwindVersion           string                       `json:"tailwindVersion"`
	ProbedNamespaces          int                          `json:"probedNamespaces"`
	DefaultSpacingSuggestions []string                     `json:"defaultSpacingSuggestions"`
	SuggestedFractions        []string                     `json:"suggestedFractions"`
	Statics                   map[string]bool              `json:"statics"`
	Functional                map[string][]suggestionGroup `json:"functional"`
}

func main() {
	input := flag.String("input", "", "path to the JSON enumerate.mjs wrote")
	output := flag.String("output", "", "path to write the generated Go file")
	check := flag.Bool("check", false, "fail if the file at -output differs from what the input renders")
	flag.Parse()

	if *input == "" || *output == "" {
		fail("-input and -output are both required")
	}
	raw, err := os.ReadFile(*input)
	if err != nil {
		fail("read %s: %v", *input, err)
	}
	var file suggestionsFile
	if err := json.Unmarshal(raw, &file); err != nil {
		fail("parse %s: %v", *input, err)
	}
	if len(file.Functional) == 0 || len(file.Statics) == 0 || len(file.DefaultSpacingSuggestions) == 0 || len(file.SuggestedFractions) == 0 {
		fail("%s is missing recipes, statics, the spacing scale or the fractions, so it is not a whole extraction", *input)
	}

	source, err := render(file)
	if err != nil {
		fail("render: %v", err)
	}

	if *check {
		existing, err := os.ReadFile(*output)
		if err != nil {
			fail("read %s: %v", *output, err)
		}
		if !bytes.Equal(existing, source) {
			fail("%s is stale: the engine's recipes changed, so regenerate it and read the diff", *output)
		}
		fmt.Fprintf(os.Stderr, "generate_suggestions: %s is current\n", *output)
		return
	}
	if err := os.WriteFile(*output, source, 0o644); err != nil {
		fail("write %s: %v", *output, err)
	}
	fmt.Fprintf(os.Stderr, "generate_suggestions: %d functional roots, %d statics\n", len(file.Functional), len(file.Statics))
}

func render(file suggestionsFile) ([]byte, error) {
	var body bytes.Buffer
	fmt.Fprintf(&body, `// Code generated by internal/lint/rules/tailwind/tools/generate_suggestions. DO NOT EDIT.
//
// Generated against Tailwind %s, probing %d theme namespaces.
//
// Every functional root's suggestion recipe, as its `+"`suggest`"+` call registers it, and every static
// with whether the class list holds it. BuildClassList resolves these against a run's theme to rebuild
// `+"`getClassList()`"+`. The recipes hold namespaces, never keys: the keys are the repository's.
//
// Regenerate with:
//
//	node internal/lint/rules/tailwind/tools/generate_suggestions/enumerate.mjs --resolve-root ahra: > suggestions.json
//	go run ./internal/lint/rules/tailwind/tools/generate_suggestions -input suggestions.json \
//	    -output internal/lint/rules/tailwind/collapse/framework_suggestions_table.go

package tailwind

// DefaultSpacingSuggestions is upstream's DEFAULT_SPACING_SUGGESTIONS, the scale a spacing root offers
// when the theme sets `+"`--spacing`"+`.
var DefaultSpacingSuggestions = %s

// SuggestedFractions is the list upstream's `+"`suggest`"+` appends for a root that supports fractions.
var SuggestedFractions = %s

// FrameworkStaticSuggested is every static the framework registers, true when the class list holds
// it. The false ones are the deprecated spellings Tailwind still compiles and no longer offers, whose
// `+"`suggest`"+` returns nothing.
var FrameworkStaticSuggested = map[string]bool{
`, file.TailwindVersion, file.ProbedNamespaces, stringSlice(file.DefaultSpacingSuggestions), stringSlice(file.SuggestedFractions))

	names := make([]string, 0, len(file.Statics))
	for name := range file.Statics {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		fmt.Fprintf(&body, "\t%s: %t,\n", strconv.Quote(name), file.Statics[name])
	}
	body.WriteString(`}

// FrameworkSuggestions is every functional root's suggestion groups, in registration order.
var FrameworkSuggestions = map[string][]SuggestionGroup{
`)

	roots := make([]string, 0, len(file.Functional))
	for root := range file.Functional {
		roots = append(roots, root)
	}
	sort.Strings(roots)
	for _, root := range roots {
		fmt.Fprintf(&body, "\t%s: {\n", strconv.Quote(root))
		for _, group := range file.Functional[root] {
			body.WriteString("\t\t{")
			if group.SupportsNegative {
				body.WriteString("SupportsNegative: true, ")
			}
			fmt.Fprintf(&body, "Values: %s, Modifiers: %s},\n", list(group.Values), list(group.Modifiers))
		}
		body.WriteString("\t},\n")
	}
	body.WriteString("}\n")

	return format.Source(body.Bytes())
}

// list renders one SuggestionList literal, leaving out the zero fields.
func list(recipe suggestionList) string {
	var fields []string
	if len(recipe.Literals) > 0 {
		fields = append(fields, "Literals: "+stringSlice(recipe.Literals))
	}
	if recipe.SpacingScale {
		fields = append(fields, "SpacingScale: true")
	}
	if len(recipe.Namespaces) > 0 {
		fields = append(fields, "Namespaces: "+stringSlice(recipe.Namespaces))
	}
	if recipe.Fractions {
		fields = append(fields, "Fractions: true")
	}
	if recipe.HasDefault {
		fields = append(fields, "HasDefault: true")
	}
	if recipe.DefaultWhenThemeKey != "" {
		fields = append(fields, "DefaultWhenThemeKey: "+strconv.Quote(recipe.DefaultWhenThemeKey))
	}
	return "SuggestionList{" + strings.Join(fields, ", ") + "}"
}

func stringSlice(values []string) string {
	quoted := make([]string, len(values))
	for index, value := range values {
		quoted[index] = strconv.Quote(value)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

func fail(format string, arguments ...any) {
	fmt.Fprintf(os.Stderr, "generate_suggestions: "+format+"\n", arguments...)
	os.Exit(1)
}
