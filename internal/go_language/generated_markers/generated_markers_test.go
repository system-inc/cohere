// staticcheckGeneratedRun is generated.Analyzer's Run as this test binary initializes it, which is staticcheck's own:
// only check replaces it, and this package never imports check. A test binary that linked check would find check's
// Run here and compare the scanner with itself, which staticcheckJudgments refuses.
var staticcheckGeneratedRun = generated.Analyzer.Run

// staticcheckPackage is the package staticcheck's own Run is declared in, which begins the name the runtime gives it.
const staticcheckPackage = "honnef.co/go/tools/analysis/facts/generated."

// staticcheckJudgments runs staticcheck's own generated.Analyzer Run over the files at paths, each parsed to its
// package clause, and ReadGeneratedMarkers over the same, answering both results.
func staticcheckJudgments(test *testing.T, paths []string) (map[string]generated.Generator,
	map[string]generated.Generator) {
	test.Helper()
	// A function compares only to nil, so the Run is known by the name the runtime gives the code it points at.
	if name := runtime.FuncForPC(reflect.ValueOf(staticcheckGeneratedRun).Pointer()).Name(); !strings.HasPrefix(name,
		staticcheckPackage) {
		test.Fatalf("generated.Analyzer's Run is %s, not staticcheck's: something in this test binary links check, "+
			"which replaces it, so the scanner would be compared with itself", name)
	}
	fileSet := token.NewFileSet()
	files := make([]*ast.File, 0, len(paths))
	for _, path := range paths {
		file, parseError := parser.ParseFile(fileSet, path, nil, parser.PackageClauseOnly)
		if parseError != nil {
			// A file whose package clause does not parse is in no pass, so neither Run ever judges it.
			continue
		}
		files = append(files, file)
	}
	pass := &analysis.Pass{Fset: fileSet, Files: files}
	staticcheckResult, staticcheckError := staticcheckGeneratedRun(pass)
	if staticcheckError != nil {
		test.Fatalf("staticcheck's Run: %v", staticcheckError)
	}
	staticcheckGenerators, staticcheckTyped := staticcheckResult.(map[string]generated.Generator)
	if !staticcheckTyped {
		test.Fatalf("staticcheck's result is %T, want map[string]generated.Generator", staticcheckResult)
	}
	return staticcheckGenerators, ReadGeneratedMarkers(pass)
}

// expectSameJudgments fails test for every file the two results judge apart.
func expectSameJudgments(test *testing.T, staticcheckGenerators map[string]generated.Generator,
	ourGenerators map[string]generated.Generator) {
	test.Helper()
	for path, generator := range staticcheckGenerators {
		ours, marked := ourGenerators[path]
		if !marked || ours != generator {
			test.Errorf("%s: staticcheck judges generator %v, ReadGeneratedMarkers %v (marked %t)", path, generator,
				ours, marked)
		}
	}
	for path, generator := range ourGenerators {
		if _, marked := staticcheckGenerators[path]; !marked {
			test.Errorf("%s: ReadGeneratedMarkers judges generator %v, staticcheck judges no marker", path, generator)
		}
	}
}

// ReadGeneratedMarkers judges each file as staticcheck's own Run does: every generator by name, a marker with a
// carriage return, at the end with no newline, after the package clause, on the first line before it, where tools
// usually write it, a marker longer than the reader's buffer gathered whole, a long line that is no marker read past,
// the prefix and suffix overlapping, the prefix with no suffix, which is no marker, and a marker inside a raw string,
// which staticcheck reads as a line like any other.
func TestReadGeneratedMarkersJudgesAsStaticcheck(test *testing.T) {
	test.Parallel()
	directory := test.TempDir()
	var paths []string
	for index, lines := range []string{
		"var x = 1\n",
		"// Code generated by goyacc. DO NOT EDIT.\r\n",
		"// Code generated by goyacc -o parser.go. DO NOT EDIT.\n",
		"// Code generated by cmd/cgo; DO NOT EDIT.",
		"// Code generated by protoc-gen-go. DO NOT EDIT.\n",
		"// Code generated by \"stringer -type=Kind\"; DO NOT EDIT.\n",
		"// Code generated by a tool of ours. DO NOT EDIT.\n",
		"// Created by cgo - DO NOT EDIT\n",
		"// Code generated by " + strings.Repeat("x", 16384) + " DO NOT EDIT.\r\n",
		"// Code generated by protoc-gen-go." + strings.Repeat(" ", 5000) + "DO NOT EDIT.\n",
		"// " + strings.Repeat("x", 16384) + "// Created by cgo - DO NOT EDIT\n",
		"// " + strings.Repeat("x", 16384) + "\n// Code generated by protoc-gen-go. DO NOT EDIT.",
		"// " + strings.Repeat("x", 16384),
		"// Code generated DO NOT EDIT.\n",
		"// Code generated by a tool of ours. Do not edit by hand.\n",
		"var s = `\n// Created by cgo - DO NOT EDIT\n`\n",
	} {
		path := filepath.Join(directory, "source"+strings.Repeat("_", index)+".go")
		if writeError := os.WriteFile(path, []byte("package fixture\n"+lines), 0o600); writeError != nil {
			test.Fatal(writeError)
		}
		paths = append(paths, path)
	}
	// The one fixture whose marker comes first, its package clause after it, where generators usually write it.
	firstLine := filepath.Join(directory, "first_line.go")
	firstLineSource := "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage fixture\n"
	if writeError := os.WriteFile(firstLine, []byte(firstLineSource), 0o600); writeError != nil {
		test.Fatal(writeError)
	}
	paths = append(paths, firstLine)
	staticcheckGenerators, ourGenerators := staticcheckJudgments(test, paths)
	if len(staticcheckGenerators) == 0 {
		test.Fatal("staticcheck judged no fixture generated, so the fixtures test nothing")
	}
	// Were staticcheck to judge it no marker, agreeing with it would test nothing about the first line.
	if _, marked := staticcheckGenerators[firstLine]; !marked {
		test.Fatal("staticcheck judged the marker on the first line no marker, so that fixture tests nothing")
	}
	expectSameJudgments(test, staticcheckGenerators, ourGenerators)
}

// A marker on a line whose read fails before its newline is no marker, as staticcheck's isGenerated reads it: the
// read's error ends the scan.
func TestScanGeneratedMarkerRefusesALineWhoseReadFailed(test *testing.T) {
	test.Parallel()
	marker := strings.NewReader("// Code generated by cmd/cgo; DO NOT EDIT.")
	source := io.MultiReader(marker, iotest.ErrReader(errors.New("the disk went away")))
	if generator, marked := ScanGeneratedMarker(source); marked {
		test.Fatalf("a marker on a line ending in a read error was judged generator %v", generator)
	}
}
