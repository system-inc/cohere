package rename

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"reflect"
	"slices"
	"testing"
)

// cgo's translation of a source file, which names it, in the directory %s, in a //line directive at its package
// clause, and a file cgo generates with no source, as _cgo_gotypes.go, which declares what the translation calls.
const (
	translationSource = "// Code generated by cmd/cgo; DO NOT EDIT.\n\n//line %s/archive.go:1:1\n" +
		"package archive\n\nfunc Twice() int {\n\tdoubled := _Cfunc_twice()\n\treturn doubled\n}\n"
	gotypesSource = "// Code generated by cmd/cgo; DO NOT EDIT.\n\npackage archive\n\n" +
		"func _Cfunc_twice() int { return 2 }\n"
)

// A package's own files outside the root are keyed by its source whose base name their //line directives name,
// whatever the build cache calls them and whatever directory the directives name: the same translation read under two
// hash names fingerprints the same, keyed by archive.go under the root, and so does one whose directives name another
// directory's archive.go, as a translation cached under -trimpath for the same bytes elsewhere does. The generated file
// with no source is left out, and the translation's call into it is keyed by kind and name, which a changed hash
// leaves alone. Keyed by the cache name the first two read as different files, and keyed by the directory the
// directives name the third is left out.
func TestAFileOutsideTheRootIsKeyedByTheSourceItTranslates(test *testing.T) {
	test.Parallel()
	sources := []string{"/root/archive/archive.go"}
	fingerprint := func(cacheName string, namedDirectory string) (map[string][]IdentifierRecord, map[string][]int) {
		fileSet := token.NewFileSet()
		var files []*ast.File
		for _, file := range []struct{ name, source string }{
			{"/cache/" + cacheName + "/translation-d", fmt.Sprintf(translationSource, namedDirectory)},
			{"/cache/" + cacheName + "/gotypes-d", gotypesSource},
		} {
			parsed, parseError := parser.ParseFile(fileSet, file.name, file.source, parser.ParseComments)
			if parseError != nil {
				test.Fatal(parseError)
			}
			files = append(files, parsed)
		}
		info := &types.Info{Defs: map[*ast.Ident]types.Object{}, Uses: map[*ast.Ident]types.Object{}}
		checked, checkError := (&types.Config{}).Check("fixture/archive", fileSet, files, info)
		if checkError != nil {
			test.Fatal(checkError)
		}
		return Fingerprint(fileSet, checked, info, files, "/root", sources),
			IdentifierOffsets(fileSet, files, "/root", sources)
	}
	before, beforeOffsets := fingerprint("c4", "/root/archive")
	after, afterOffsets := fingerprint("45", "/root/archive")
	if !reflect.DeepEqual(before, after) || !reflect.DeepEqual(beforeOffsets, afterOffsets) {
		test.Fatalf("the same files under two cache names fingerprint differently:\n%v\n%v", before, after)
	}
	// Its offsets are into the file as read, which a longer directive moves, and are never compared: an edit, the
	// only thing matched against them, is never made in a translation.
	elsewhere, elsewhereOffsets := fingerprint("e0", "/elsewhere/archive")
	if !reflect.DeepEqual(before, elsewhere) || len(elsewhereOffsets["/root/archive/archive.go"]) !=
		len(beforeOffsets["/root/archive/archive.go"]) {
		test.Fatalf("a translation naming another directory fingerprints otherwise:\n%v\n%v", before, elsewhere)
	}
	records, keyed := before["/root/archive/archive.go"]
	if !keyed || len(before) != 1 || len(beforeOffsets) != 1 {
		test.Fatalf("want archive.go alone keyed, got %v", before)
	}
	want := IdentifierRecord{Name: "_Cfunc_twice", Key: "-|here:generated func _Cfunc_twice"}
	if !slices.Contains(records, want) {
		test.Errorf("want the call into the generated file read as %+v, got %+v", want, records)
	}
}
