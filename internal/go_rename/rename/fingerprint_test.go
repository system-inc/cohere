package rename

import (
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"reflect"
	"slices"
	"testing"
)

// cgo's translation of a source file, which names it in a //line directive at its package clause, and a file cgo
// generates with no source, as _cgo_gotypes.go, which declares what the translation calls.
const (
	translationSource = "// Code generated by cmd/cgo; DO NOT EDIT.\n\n//line /root/archive/archive.go:1:1\n" +
		"package archive\n\nfunc Twice() int {\n\tdoubled := _Cfunc_twice()\n\treturn doubled\n}\n"
	gotypesSource = "// Code generated by cmd/cgo; DO NOT EDIT.\n\npackage archive\n\n" +
		"func _Cfunc_twice() int { return 2 }\n"
)

// A package's own files outside the root are keyed by the source their //line directives name, whatever the build
// cache calls them: the same translation read under two hash names fingerprints the same, keyed by archive.go. The
// generated file with no source under the root is left out, and the translation's call into it is keyed by kind and
// name, which a changed hash leaves alone. Keyed by the cache name, the two read as different files.
func TestAFileOutsideTheRootIsKeyedByTheSourceItTranslates(test *testing.T) {
	test.Parallel()
	fingerprint := func(cacheName string) (map[string][]IdentifierRecord, map[string][]int) {
		fileSet := token.NewFileSet()
		var files []*ast.File
		for _, file := range []struct{ name, source string }{
			{"/cache/" + cacheName + "/translation-d", translationSource},
			{"/cache/" + cacheName + "/gotypes-d", gotypesSource},
		} {
			parsed, parseError := parser.ParseFile(fileSet, file.name, file.source, parser.ParseComments)
			if parseError != nil {
				test.Fatal(parseError)
			}
			files = append(files, parsed)
		}
		info := &types.Info{Defs: map[*ast.Ident]types.Object{}, Uses: map[*ast.Ident]types.Object{}}
		checked, checkError := (&types.Config{}).Check("fixture/archive", fileSet, files, info)
		if checkError != nil {
			test.Fatal(checkError)
		}
		return Fingerprint(fileSet, checked, info, files, "/root"), IdentifierOffsets(fileSet, files, "/root")
	}
	before, beforeOffsets := fingerprint("c4")
	after, afterOffsets := fingerprint("45")
	if !reflect.DeepEqual(before, after) || !reflect.DeepEqual(beforeOffsets, afterOffsets) {
		test.Fatalf("the same files under two cache names fingerprint differently:\n%v\n%v", before, after)
	}
	records, keyed := before["/root/archive/archive.go"]
	if !keyed || len(before) != 1 || len(beforeOffsets) != 1 {
		test.Fatalf("want archive.go alone keyed, got %v", before)
	}
	want := IdentifierRecord{Name: "_Cfunc_twice", Key: "-|here:generated func _Cfunc_twice"}
	if !slices.Contains(records, want) {
		test.Errorf("want the call into the generated file read as %+v, got %+v", want, records)
	}
}
