package documentation_data

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
)

// RuleNamesPath is the Go file Build writes beside the website's data: every engine's rule names, in rules.json's
// order, for the program that needs them. The Go engine's file-name rule and the folder check in discovery read
// them, since cohere's Go source names a file for the rule it ports and the Go engine can't link the TypeScript
// registry (#2xt6v5r). They are Go rather than an embed of rules.json, because a package in documentation/ would be
// named documentation, which the go command ignores, and so nothing is decoded at run time (#zyq63kk).
const RuleNamesPath = "internal/rule_names/rule_names.generated.go"

// renderRuleNames writes rules' names as the rule_names package's source, gofmt'd, so the file is the same bytes
// for the same rows.
func renderRuleNames(rules Rules) ([]byte, error) {
	var source bytes.Buffer
	source.WriteString("// Code generated by go run ./internal/documentation_data/tools/generate. DO NOT EDIT.\n\n")
	source.WriteString("// Package rule_names holds every engine's rule names, as documentation/data/rules.json\n")
	source.WriteString("// lists them, in its order: a TypeScript port's upstream name, and each engine's house\n")
	source.WriteString("// rules.\n")
	source.WriteString("package rule_names\n\n")
	source.WriteString("// names are the rule names, in rules.json's order.\n")
	source.WriteString("var names = []string{\n")
	for _, row := range rules.Rules {
		source.WriteString("\t" + strconv.Quote(row.Name) + ",\n")
	}
	source.WriteString("}\n\n")
	source.WriteString("// RuleNames returns every engine's rule names, a copy a caller may change.\n")
	source.WriteString("func RuleNames() []string {\n\treturn append([]string(nil), names...)\n}\n")
	formatted, formatError := format.Source(source.Bytes())
	if formatError != nil {
		return nil, fmt.Errorf("documentation_data: %s: %w", RuleNamesPath, formatError)
	}
	return formatted, nil
}
