package fact_reach

import "github.com/system-inc/go-types/types"

// BodyRecord is what one function body holds that a presence row reads and no use of stage 1's record says, as the
// host reads it off its own syntax (standing_presence.ReadBodies): the functions of the package the body starts with
// go where testinggoroutine hears the statement, and those it hands by name to (*testing.T).Run in a _test.go file,
// each once, in the order the body names them; whether it writes a candidate of consistency-no-any's of its own; and
// the method names of the marker interfaces it declares, sorted. The host renders each function's key
// (PresenceRecord). It lives here, beside the record it renders to, so the host's run holds it without importing the
// rules package that reads it (#f5g7ym6).
type BodyRecord struct {
	GoStarts     []*types.Func
	RunStarts    []*types.Func
	OwnAny       bool
	LocalMarkers []string
}
