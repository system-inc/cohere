// lineClaimPackage is the ID of the body-reach-line-claims fixture's own package, the one each case writes target.go
// into.
const lineClaimPackage = "example.test/audit"

// generatedMarker is staticcheck's generated marker on a line of its own, which staticcheck reads anywhere in a file.
const generatedMarker = "\n// Code generated by audit. DO NOT EDIT.\n"

// declaringPlatformFiles are a package's two platform files, part_windows.go, windows's, and part_other.go, every
// platform's but windows's, each declaring other with the generated marker in its body, so each is generated in the
// one build that compiles it.
var declaringPlatformFiles = map[string]string{
	"part_windows.go": "package audit\n\n// other is windows's.\nfunc other() int {" + generatedMarker +
		"\treturn 1\n}\n",
	"part_other.go": "//go:build !windows\n\npackage audit\n\n// other is every platform's but windows's.\n" +
		"func other() int {" + generatedMarker + "\treturn 1\n}\n",
}

// barePlatformFiles are the two platform files declaring nothing, each generated by the marker after its package
// clause, so nothing but a claim tells the builds apart: no body, no name and no initializer is one side's alone.
var barePlatformFiles = map[string]string{
	"part_windows.go": "package audit\n" + generatedMarker,
	"part_other.go":   "//go:build !windows\n\npackage audit\n" + generatedMarker,
}

// hostTestFile is an in-package test file every platform but windows compiles, generated, and windowsTestFile
// windows's, generated too.
var (
	hostTestFile = map[string]string{"helper_other_test.go": "//go:build !windows\n\npackage audit\n\n" +
		"// othertest is every platform's but windows's.\nfunc othertest() int {" + generatedMarker +
		"\treturn 1\n}\n"}
	windowsTestFile = map[string]string{"helper_windows_test.go": "package audit\n\n// othertest is windows's.\n" +
		"func othertest() int {" + generatedMarker + "\treturn 1\n}\n"}
)

// anchorFiles are a package of its own with a file of windows's, so the run checks a windows build whatever the case's
// own package holds.
var anchorFiles = map[string]string{
	"anchor/part_windows.go": "package anchor\n\n// Name is windows's.\nfunc Name() string { return \"windows\" }\n",
	"anchor/part_other.go": "//go:build !windows\n\npackage anchor\n\n// Name is every platform's but windows's.\n" +
		"func Name() string { return \"other\" }\n",
}

// A `//line` directive moves the positions after it, and a rule reads the file name it moves them to: staticcheck's
// generated-file filter asks whether the file a finding's position claims is generated, by the files the package
// compiles (#d2mqgfj, wave 4's N1). The body-reach-line-claims fixture is the auditor's module: a shared target under
// `//line` naming a platform file, generated on that platform alone, and a quiet package. SA4003's finding in target
// is then filtered in the build that compiles the generated sibling and reported in the build that does not, though
// nothing target uses differs. The reach reaches a body whose positions claim a file the builds do not share,
// LineClaim, so it is never compared and never stands. Each case is judged three ways: by windows's census, by the
// body differential, which must read no failure, and by the second check, windows's own findings with the standing
// bodies' switch off against on, which must be alike. And no body of any case may be reached by the general load
// mode rule alone, which a claimed body would be if the claim were not the constants-only rule's reason too.
//
// The first four are the claim inside the body: of windows's file, of the host's platform's, of windows's again below
// a directive naming target's own file, which moves the line the claiming directive is read at and claims nothing
// itself, and of a generated file both builds compile, where the filter withholds the finding in both, so target is
// left unreached, compared, and alike.
//
// Then a claim of a test file one build alone compiles (the Square's must 1). The host lints target in its test
// variant, whose list holds the test file, and windows, with no test file, lints it in the plain package, which the
// census pairs with the host's plain one: neither list of that ID holds the test file, so the claim is seen only by
// the lists of every package that compiles target, taken together. Where both builds have test files, each lints
// target in its variant and the one ID's lists see the claim, in a plain file and in a test file. Where windows alone
// has a test file, its variant has no package of the host's, so the census judges none of it and windows lints it
// whole.
//
// Then the forms a claim takes, each beside what would hide it were the form unseen. A value spec, and a const group
// under one directive, beside platform files that declare nothing, so no initializer is reached for another reason.
// The block form, in the middle of a line and before the `func`. A directive above the `func` beside platform files
// that declare nothing: where the claimed file declares a function, the side that compiles it asks two files' bodies
// under one name and lints the package whole (rule.StandingSpans), so only a bare sibling leaves the body to the
// second check. A later directive ending a claim: released, whose directive a blank line parts from it, is under no
// claim, while adjoined, whose directive is written directly above it, is claimed by the claim before, since that
// directive is its doc comment and lies under that claim. And a claim over a doc comment alone, which a directive
// ends before the `func`.
func TestTheReachReachesABodyWhoseLineDirectiveClaimsAnUnsharedFile(test *testing.T) {
	test.Parallel()

	// inside is target with before, then a directive claiming claimed, in its body.
	inside := func(before string, claimed string) string {
		return "package audit\n\n// target compares an unsigned value with zero, under a claim of a platform file.\n" +
			"func target(value uint8) bool {\n" + before + "//line " + claimed + ":7:2\n\treturn value >= 0\n}\n"
	}
	// above is target under a directive claiming claimed at line, written above its `func`.
	above := func(claimed string, line string) string {
		return "package audit\n\n//line " + claimed + ":" + line + "\nfunc target(value uint8) bool {\n" +
			"\treturn value >= 0\n}\n"
	}
	// compares is a function literal comparing an unsigned value with zero.
	const compares = "func(value uint8) bool { return value >= 0 }"
	// variant is the ID of the fixture's package with its in-package tests.
	const variant = lineClaimPackage + " [" + lineClaimPackage + ".test]"
	claimed, unreached := string(reachedLineClaim), "unreached"
	for _, each := range []struct {
		name string
		// files are the files the case writes over the fixture, by path.
		files map[string]string
		// identifier is the ID of the package whose bodies want names, the fixture's own package's when empty.
		identifier string
		// want is how windows's census must judge each body it names.
		want map[string]string
	}{
		{name: "claiming windows's file", files: filesWith(inside("", "part_windows.go"), declaringPlatformFiles),
			want: map[string]string{"target": claimed}},
		{name: "claiming the host's platform's file",
			files: filesWith(inside("", "part_other.go"), declaringPlatformFiles),
			want:  map[string]string{"target": claimed}},
		// The directive before the claim names target's own file at a line past the file's last, with a statement
		// under it.
		{name: "claiming windows's file below a directive that moves its line",
			files: filesWith(inside("//line target.go:900\n\t_ = value\n", "part_windows.go"),
				declaringPlatformFiles),
			want: map[string]string{"target": claimed}},
		{name: "claiming a file both builds compile", files: filesWith(inside("", "sibling.go"),
			declaringPlatformFiles, map[string]string{"sibling.go": "package audit\n\n// sibling is every build's.\n" +
				"func sibling() int {" + generatedMarker + "\treturn 2\n}\n"}),
			want: map[string]string{"target": unreached}},

		{name: "claiming a test file the host alone compiles, inside the body", files: filesWith("package audit\n\n"+
			"func target(value uint8) bool {\n//line helper_other_test.go:5\n\treturn value >= 0\n}\n", hostTestFile,
			anchorFiles), want: map[string]string{"target": claimed}},
		{name: "claiming a test file the host alone compiles, above the func",
			files: filesWith(above("helper_other_test.go", "20"), hostTestFile, anchorFiles),
			want:  map[string]string{"target": claimed}},
		{name: "claiming windows's test file where both builds have test files",
			files: filesWith(above("helper_windows_test.go", "7"), hostTestFile, windowsTestFile,
				declaringPlatformFiles),
			identifier: variant, want: map[string]string{"target": claimed}},
		{name: "a test file claiming the host's test file where both builds have test files",
			files: map[string]string{
				"target_test.go":         above("helper_other_test.go", "7"),
				"plain.go":               "package audit\n\n// Plain is every build's.\nfunc Plain() int { return 1 }\n",
				"helper_other_test.go":   hostTestFile["helper_other_test.go"],
				"helper_windows_test.go": windowsTestFile["helper_windows_test.go"],
			},
			identifier: variant, want: map[string]string{"target": claimed}},
		{name: "claiming a test file windows alone compiles",
			files: filesWith(above("helper_windows_test.go", "7"), windowsTestFile),
			want:  map[string]string{"target": "unjudged"}},

		{name: "a value spec claiming the host's platform's file, which declares nothing",
			files: filesWith("package audit\n\n//line part_other.go:7\nvar hook = "+compares+"\n", barePlatformFiles),
			want:  map[string]string{"hook": claimed}},
		{name: "a const group claiming windows's file, which declares nothing",
			files: filesWith("package audit\n\nconst limit uint8 = 3\n\n//line part_windows.go:7\nconst (\n"+
				"\tfirst = limit >= 0\n\tsecond\n)\n", barePlatformFiles),
			want: map[string]string{"limit": unreached, "first": claimed, "second": claimed}},
		{name: "a block directive in the middle of a line", files: filesWith("package audit\n\n"+
			"func target(value uint8) bool { return /*line part_other.go:7:2*/ value >= 0 }\n",
			declaringPlatformFiles), want: map[string]string{"target": claimed}},
		{name: "a block directive before the func, claiming a file that declares nothing",
			files: filesWith("package audit\n\n/*line part_windows.go:7:1*/ func target(value uint8) bool { return "+
				"value >= 0 }\n", barePlatformFiles),
			want: map[string]string{"target": claimed}},
		{name: "a directive above the func, claiming a file that declares nothing",
			files: filesWith(above("part_other.go", "7"), barePlatformFiles),
			want:  map[string]string{"target": claimed}},
		{name: "a later directive ending a claim", files: filesWith("package audit\n\n"+
			"//line part_other.go:7\nfunc claimed(value uint8) bool {\n\treturn value >= 0\n}\n\n"+
			"//line target.go:20\n\nfunc released(value uint8) bool {\n\treturn value >= 0\n}\n\n"+
			"//line part_other.go:30\nfunc again(value uint8) bool {\n\treturn value >= 0\n}\n\n"+
			"//line target.go:50\nfunc adjoined(value uint8) bool {\n\treturn value >= 0\n}\n",
			declaringPlatformFiles),
			want: map[string]string{"claimed": claimed, "released": unreached, "again": claimed,
				"adjoined": claimed}},
		{name: "a claim over a doc comment alone", files: filesWith("package audit\n\n//line part_other.go:7\n"+
			"// target compares.\n//line target.go:6\nfunc target(value uint8) bool {\n\treturn value >= 0\n}\n",
			barePlatformFiles), want: map[string]string{"target": claimed}},
	} {
		test.Run(each.name, func(test *testing.T) {
			test.Parallel()

			census, failures := runLineClaims(test, each.files)
			for name, want := range each.want {
				if reason := judgedBody(census, cmp.Or(each.identifier, lineClaimPackage), name); reason != want {
					test.Errorf("windows's census judges %s %s, want %s", name, reason, want)
				}
			}
			for _, body := range census.bodies {
				if body.reason != "" && body.constantsOnlyReason == "" {
					test.Errorf("windows's census reaches %s by the general load mode rule alone, want no body so",
						body.name)
				}
			}
			if len(failures) > 0 {
				test.Errorf("want the body differential to read no failure, got\n%s", strings.Join(failures, "\n"))
			}
			off, on := standingLineClaims(test, each.files)
			if !slices.Equal(off, on) {
				test.Errorf("want windows's own findings alike with the standing bodies' switch off and on, got\n"+
					"lost with it on:\n%s\ninvented with it on:\n%s", strings.Join(lacking(off, on), "\n"),
					strings.Join(lacking(on, off), "\n"))
			}
		})
	}
}

// A finding is placed by the file as parsed at its line as written (check.newFinding), so the body differential reads
// a compared body's findings there, whatever a `//line` directive moves the body's positions to (#99saas4, the
// Square's M2). Read in the file the positions claim at the moved lines, a body under a directive is compared by
// another file's findings, or by another body's: a failure where its own are alike, and silence where they differ.
//
// The first case is a target the cure rightly leaves unreached, under a claim of another package's file, which the
// host alone compiles and holds findings in: both builds hold SA4003 in target, and target's lines as written and as
// moved both cover the generated marker's line of that file, so reading that file by either fails. The second is a
// body its directive moves onto the lines of another body of its own file, one a claim reaches and whose SA4003 only
// windows holds: its own findings are alike. A blank line parts that directive from the body, or it would be the
// body's doc comment, under the claim before it, and the body claimed too. The silence, a body whose findings differ
// read where nothing is, was a claim of a test file the host alone compiles, which the reach now reaches (the reach's
// own test's cases of it), so no body left to compare shows it.
func TestTheBodyDifferentialReadsABodysFindingsWhereTheyArePlaced(test *testing.T) {
	test.Parallel()

	for _, each := range []struct {
		name  string
		files map[string]string
		// body is the body of the case's package the differential must compare, unreached.
		body string
	}{
		{name: "a claim of another package's file", body: "target", files: filesWith("package audit\n\n"+
			"//line generated/part_other.go:7\nfunc target(value uint8) bool {\n\tresult := value >= 0\n"+
			"\treturn result\n}\n", map[string]string{
			"generated/part_windows.go": "package generated\n\n// other is windows's.\nfunc other() int {" +
				generatedMarker + "\treturn 1\n}\n",
			"generated/part_other.go": "//go:build !windows\n\npackage generated\n\n// other is every platform's " +
				"but windows's.\nfunc other() int {" + generatedMarker + "\treturn 1\n}\n",
			"generated/quiet.go": "package generated\n\n// Quiet is every build's.\nfunc Quiet() int { return " +
				"other() }\n",
		})},
		{name: "a body moved onto another body's lines", body: "moved", files: filesWith("package audit\n\n"+
			"func claimed(value uint8) bool {\n//line part_other.go:7:2\n\treturn value >= 0\n}\n\n"+
			"//line target.go:3\n\nfunc moved(value uint8) bool {\n\treturn value >= 0\n}\n", declaringPlatformFiles)},
	} {
		test.Run(each.name, func(test *testing.T) {
			test.Parallel()

			census, failures := runLineClaims(test, each.files)
			if reason := judgedBody(census, lineClaimPackage, each.body); reason != "unreached" {
				test.Fatalf("windows's census judges %s %s, want it unreached, so compared", each.body, reason)
			}
			if len(failures) > 0 {
				test.Errorf("want the body differential to read no failure, got\n%s", strings.Join(failures, "\n"))
			}
		})
	}
}

// filesWith are the files of a case: target as target.go, and every file of others, by path.
func filesWith(target string, others ...map[string]string) map[string]string {
	files := map[string]string{"target.go": target}
	for _, other := range others {
		maps.Copy(files, other)
	}
	return files
}

// writeLineClaimFiles copies the body-reach-line-claims fixture, writes files over the copy, each by its path under
// the root, and returns the copy's root.
func writeLineClaimFiles(test *testing.T, files map[string]string) string {
	test.Helper()
	root := copyFixture(test, filepath.Join("testdata", "body-reach-line-claims"))
	for name, contents := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if makeError := os.MkdirAll(filepath.Dir(path), 0o755); makeError != nil {
			test.Fatal(makeError)
		}
		if writeError := os.WriteFile(path, []byte(contents), 0o644); writeError != nil {
			test.Fatal(writeError)
		}
	}
	return root
}

// runLineClaims runs the engine over a copy of the body-reach-line-claims fixture with files written over it
// (writeLineClaimFiles), under the census and the body differential, and returns windows's census and its
// differential's failures, the copy's root taken out of each.
func runLineClaims(test *testing.T, files map[string]string) (*buildBodyReach, []string) {
	test.Helper()
	root := writeLineClaimFiles(test, files)
	on, _ := runOverConfigured(test, root, exitFindings, func(engine *pipeline) {
		engine.bodyReachCensus = filepath.Join(test.TempDir(), "reach.txt")
		engine.bodyDifferential = true
	}, "--no-cache", "--no-fix", "--build-dependence")
	if len(on.buildRuns) != 2 || on.buildRuns[1].build.OperatingSystem != "windows" {
		test.Fatalf("want the host's build and windows's, got %d runs", len(on.buildRuns))
	}
	census, differential := on.buildRuns[1].bodyReach, on.buildRuns[1].bodyDifferential
	if census == nil || differential == nil {
		test.Fatal("windows's run has no census or no body differential")
	}
	failures := make([]string, 0, len(differential.failures))
	for _, failure := range differential.failures {
		failures = append(failures, strings.ReplaceAll(failure, root+string(filepath.Separator), ""))
	}
	return census, failures
}

// standingLineClaims runs the engine twice more, each over a copy of the body-reach-line-claims fixture with files
// written over it, under the census with the standing bodies' switch off, then on, and returns windows's own findings
// of each run (rawFindings): the second check, which sees a body left standing whose findings are not the host's.
func standingLineClaims(test *testing.T, files map[string]string) (off []string, on []string) {
	test.Helper()
	var found [2][]string
	for index, switched := range []bool{false, true} {
		root := writeLineClaimFiles(test, files)
		standing, _ := runOverConfigured(test, root, exitFindings, func(engine *pipeline) {
			engine.bodyReachCensus = filepath.Join(test.TempDir(), "reach.txt")
			engine.standingBodies = switched
		}, "--no-cache", "--no-fix", "--build-dependence")
		if len(standing.buildRuns) != 2 || standing.buildRuns[1].build.OperatingSystem != "windows" {
			test.Fatalf("want the host's build and windows's, got %d runs", len(standing.buildRuns))
		}
		found[index] = rawFindings(standing.buildRuns[1], root)
	}
	return found[0], found[1]
}

// lacking are the lines of held that other lacks, in held's order.
func lacking(held []string, other []string) []string {
	var lacked []string
	for _, line := range held {
		if !slices.Contains(other, line) {
			lacked = append(lacked, line)
		}
	}
	return lacked
}

// judgedBody is how census judges the body named name of the package identified by packageIdentifier: its reason,
// unreached for a body it leaves to the host's findings, and unjudged for one it holds no judgment of.
func judgedBody(census *buildBodyReach, packageIdentifier string, name string) string {
	for _, body := range census.bodies {
		if body.packageIdentifier == packageIdentifier && body.name == name {
			if body.reason == "" {
				return "unreached"
			}
			return string(body.reason)
		}
	}
	return "unjudged"
}
