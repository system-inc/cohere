// lineClaimPackage is the ID of the body-reach-line-claims fixture's own package, the one each case writes target.go
// into.
const lineClaimPackage = "example.test/audit"

// generatedMarker is staticcheck's generated marker on a line of its own, which staticcheck reads anywhere in a file.
const generatedMarker = "\n// Code generated by audit. DO NOT EDIT.\n"

// declaringPlatformFiles are a package's two platform files, part_windows.go, windows's, and part_other.go, every
// platform's but windows's, each declaring other with the generated marker in its body, so each is generated in the
// one build that compiles it.
var declaringPlatformFiles = map[string]string{
	"part_windows.go": "package audit\n\n// other is windows's.\nfunc other() int {" + generatedMarker +
		"\treturn 1\n}\n",
	"part_other.go": "//go:build !windows\n\npackage audit\n\n// other is every platform's but windows's.\n" +
		"func other() int {" + generatedMarker + "\treturn 1\n}\n",
}

// anchorFiles are a package of its own with a file of windows's, so the run checks a windows build whatever the case's
// own package holds.
var anchorFiles = map[string]string{
	"anchor/part_windows.go": "package anchor\n\n// Name is windows's.\nfunc Name() string { return \"windows\" }\n",
	"anchor/part_other.go": "//go:build !windows\n\npackage anchor\n\n// Name is every platform's but windows's.\n" +
		"func Name() string { return \"other\" }\n",
}

// A `//line` directive moves the positions after it, and a rule reads the file name it moves them to: staticcheck's
// generated-file filter asks whether the file a finding's position claims is generated, by the files the package
// compiles (#d2mqgfj, wave 4's N1). The body-reach-line-claims fixture is the auditor's module: a shared target under
// `//line` naming a platform file, generated on that platform alone, and a quiet package. SA4003's finding in target
// is then filtered in the build that compiles the generated sibling and reported in the build that does not, though
// nothing target uses differs. The reach reaches a body whose positions claim a file the builds do not share,
// LineClaim, so target is never compared and the body differential reads no failure, the claim naming windows's file,
// then the host's platform's, then windows's again below a directive naming target's own file, which moves the line
// the claiming directive is read at and claims nothing itself. The last case claims a generated file both builds
// compile: the filter withholds the finding in both, so target is left unreached, compared, and alike.
func TestTheReachReachesABodyWhoseLineDirectiveClaimsAnUnsharedFile(test *testing.T) {
	test.Parallel()

	// inside is target with before, then a directive claiming claimed, in its body.
	inside := func(before string, claimed string) string {
		return "package audit\n\n// target compares an unsigned value with zero, under a claim of a platform file.\n" +
			"func target(value uint8) bool {\n" + before + "//line " + claimed + ":7:2\n\treturn value >= 0\n}\n"
	}
	for _, each := range []struct {
		name string
		// files are the files the case writes over the fixture, by path.
		files map[string]string
		// want is how windows's census must judge each body of the case's package it names.
		want map[string]string
	}{
		{"claiming windows's file", filesWith(inside("", "part_windows.go"), declaringPlatformFiles),
			map[string]string{"target": string(reachedLineClaim)}},
		{"claiming the host's platform's file", filesWith(inside("", "part_other.go"), declaringPlatformFiles),
			map[string]string{"target": string(reachedLineClaim)}},
		// The directive before the claim names target's own file at a line past the file's last, with a statement
		// under it.
		{"claiming windows's file below a directive that moves its line",
			filesWith(inside("//line target.go:900\n\t_ = value\n", "part_windows.go"), declaringPlatformFiles),
			map[string]string{"target": string(reachedLineClaim)}},
		{"claiming a file both builds compile", filesWith(inside("", "sibling.go"), declaringPlatformFiles,
			map[string]string{"sibling.go": "package audit\n\n// sibling is every build's.\nfunc sibling() int {" +
				generatedMarker + "\treturn 2\n}\n"}),
			map[string]string{"target": "unreached"}},
	} {
		test.Run(each.name, func(test *testing.T) {
			test.Parallel()

			census, failures := runLineClaims(test, each.files)
			for name, want := range each.want {
				if reason := judgedBody(census, lineClaimPackage, name); reason != want {
					test.Errorf("windows's census judges %s %s, want %s", name, reason, want)
				}
			}
			if len(failures) > 0 {
				test.Errorf("want the body differential to read no failure, got\n%s", strings.Join(failures, "\n"))
			}
		})
	}
}

// A finding is placed by the file as parsed at its line as written (check.newFinding), so the body differential reads
// a compared body's findings there, whatever a `//line` directive moves the body's positions to (#99saas4, the
// Square's M2). Read in the file the positions claim at the moved lines, a body under a directive is compared by
// another file's findings, or by another body's: a failure where its own are alike, and silence where they differ.
//
// The first case is a target the cure rightly leaves unreached, under a claim of another package's file, which the
// host alone compiles and holds findings in: both builds hold SA4003 in target, and target's lines as written and as
// moved both cover the generated marker's line of that file, so reading that file by either fails. The second is the
// silence: a claim of a test file the host alone compiles, above the `func`, which the reach does not yet see, so
// SA4003 is windows's alone and the differential must say so. It fails here, wanted: #d2mqgfj's must 1 reaches that
// body, and its case then reads no failure. The third is a body its directive moves onto the lines of another body
// of its own file, one a claim reaches and whose SA4003 only windows holds: its own findings are alike.
func TestTheBodyDifferentialReadsABodysFindingsWhereTheyArePlaced(test *testing.T) {
	test.Parallel()

	for _, each := range []struct {
		name  string
		files map[string]string
		// body is the body of the case's package the differential must compare, unreached.
		body string
		// wantBuildAlone is a finding the one failure must hold on the build's side alone, of body, as the
		// differential writes it, empty for a case that must read no failure.
		wantBuildAlone string
	}{
		{name: "a claim of another package's file", body: "target", files: filesWith("package audit\n\n"+
			"//line generated/part_other.go:7\nfunc target(value uint8) bool {\n\tresult := value >= 0\n"+
			"\treturn result\n}\n", map[string]string{
			"generated/part_windows.go": "package generated\n\n// other is windows's.\nfunc other() int {" +
				generatedMarker + "\treturn 1\n}\n",
			"generated/part_other.go": "//go:build !windows\n\npackage generated\n\n// other is every platform's " +
				"but windows's.\nfunc other() int {" + generatedMarker + "\treturn 1\n}\n",
			"generated/quiet.go": "package generated\n\n// Quiet is every build's.\nfunc Quiet() int { return " +
				"other() }\n",
		})},
		{name: "a claim of a test file the host alone compiles", body: "target", files: filesWith("package audit\n\n"+
			"//line helper_other_test.go:20\nfunc target(value uint8) bool {\n\treturn value >= 0\n}\n", anchorFiles,
			map[string]string{"helper_other_test.go": "//go:build !windows\n\npackage audit\n\n// othertest is " +
				"every platform's but windows's.\nfunc othertest() int {" + generatedMarker + "\treturn 1\n}\n"}),
			wantBuildAlone: "SA4003 5:9 every value of type uint8 is >= 0"},
		{name: "a body moved onto another body's lines", body: "moved", files: filesWith("package audit\n\n"+
			"func claimed(value uint8) bool {\n//line part_other.go:7:2\n\treturn value >= 0\n}\n\n"+
			"//line target.go:3\nfunc moved(value uint8) bool {\n\treturn value >= 0\n}\n", declaringPlatformFiles)},
	} {
		test.Run(each.name, func(test *testing.T) {
			test.Parallel()

			census, failures := runLineClaims(test, each.files)
			if reason := judgedBody(census, lineClaimPackage, each.body); reason != "unreached" {
				test.Fatalf("windows's census judges %s %s, want it unreached, so compared", each.body, reason)
			}
			if each.wantBuildAlone == "" {
				if len(failures) > 0 {
					test.Errorf("want the body differential to read no failure, got\n%s", strings.Join(failures, "\n"))
				}
				return
			}
			if len(failures) != 1 {
				test.Fatalf("want the body differential to read one failure, of %s, got %d\n%s", each.body,
					len(failures), strings.Join(failures, "\n"))
			}
			hostWritten, builtWritten, isDifference := strings.Cut(failures[0], "], build [")
			if !isDifference || !strings.Contains(failures[0], " "+each.body+": findings differ: host [") ||
				strings.Contains(hostWritten, each.wantBuildAlone) ||
				!strings.Contains(builtWritten, each.wantBuildAlone) {
				test.Errorf("want the failure to hold %q of %s on the build's side alone, got\n%s",
					each.wantBuildAlone, each.body, failures[0])
			}
		})
	}
}

// filesWith are the files of a case: target as target.go, and every file of others, by path.
func filesWith(target string, others ...map[string]string) map[string]string {
	files := map[string]string{"target.go": target}
	for _, other := range others {
		maps.Copy(files, other)
	}
	return files
}

// writeLineClaimFiles copies the body-reach-line-claims fixture, writes files over the copy, each by its path under
// the root, and returns the copy's root.
func writeLineClaimFiles(test *testing.T, files map[string]string) string {
	test.Helper()
	root := copyFixture(test, filepath.Join("testdata", "body-reach-line-claims"))
	for name, contents := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if makeError := os.MkdirAll(filepath.Dir(path), 0o755); makeError != nil {
			test.Fatal(makeError)
		}
		if writeError := os.WriteFile(path, []byte(contents), 0o644); writeError != nil {
			test.Fatal(writeError)
		}
	}
	return root
}

// runLineClaims runs the engine over a copy of the body-reach-line-claims fixture with files written over it
// (writeLineClaimFiles), under the census and the body differential, and returns windows's census and its
// differential's failures, the copy's root taken out of each.
func runLineClaims(test *testing.T, files map[string]string) (*buildBodyReach, []string) {
	test.Helper()
	root := writeLineClaimFiles(test, files)
	on, _ := runOverConfigured(test, root, exitFindings, func(engine *pipeline) {
		engine.bodyReachCensus = filepath.Join(test.TempDir(), "reach.txt")
		engine.bodyDifferential = true
	}, "--no-cache", "--no-fix", "--build-dependence")
	if len(on.buildRuns) != 2 || on.buildRuns[1].build.OperatingSystem != "windows" {
		test.Fatalf("want the host's build and windows's, got %d runs", len(on.buildRuns))
	}
	census, differential := on.buildRuns[1].bodyReach, on.buildRuns[1].bodyDifferential
	if census == nil || differential == nil {
		test.Fatal("windows's run has no census or no body differential")
	}
	failures := make([]string, 0, len(differential.failures))
	for _, failure := range differential.failures {
		failures = append(failures, strings.ReplaceAll(failure, root+string(filepath.Separator), ""))
	}
	return census, failures
}

// judgedBody is how census judges the body named name of the package identified by packageIdentifier: its reason,
// unreached for a body it leaves to the host's findings, and unjudged for one it holds no judgment of.
func judgedBody(census *buildBodyReach, packageIdentifier string, name string) string {
	for _, body := range census.bodies {
		if body.packageIdentifier == packageIdentifier && body.name == name {
			if body.reason == "" {
				return "unreached"
			}
			return string(body.reason)
		}
	}
	return "unjudged"
}
