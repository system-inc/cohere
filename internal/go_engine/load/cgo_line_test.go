package load

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"testing"
)

// cgoOutputFormat is a cgo output as the cgo tool writes one, its `//line` directive naming the file %s, and a
// `/*line :line:column*/` one without a file, which keeps the file the line form named.
const cgoOutputFormat = "// Code generated by cmd/cgo; DO NOT EDIT.\n\n//line %s:1:1\npackage native\n\n" +
	"// Twice is two.\nfunc Twice() int {\n\treturn /*line :7:9*/ 2\n}\n"

// cgoLinePackage is a package directory holding native.go, its one cgo file, and other.go, a Go file without cgo,
// which exists so that only its not being a cgo file keeps a directive naming it from being rewritten.
func cgoLinePackage(test *testing.T) *listedPackage {
	test.Helper()
	directory := test.TempDir()
	for _, name := range []string{"native.go", "other.go"} {
		if writeError := os.WriteFile(filepath.Join(directory, name), []byte("package native\n"),
			0o644); writeError != nil {
			test.Fatal(writeError)
		}
	}
	return &listedPackage{ImportPath: "example.com/native", Directory: directory, CgoFiles: []string{"native.go"}}
}

// positionsOf is the position of every declaration and return statement of a parse of contents, in order.
func positionsOf(test *testing.T, contents []byte) []token.Position {
	test.Helper()
	fileSet := token.NewFileSet()
	file, parseError := parser.ParseFile(fileSet, "/cache/output-d", contents, parser.ParseComments)
	if parseError != nil {
		test.Fatal(parseError)
	}
	var positions []token.Position
	ast.Inspect(file, func(each ast.Node) bool {
		switch each.(type) {
		case *ast.FuncDecl, *ast.ReturnStmt, *ast.BasicLit:
			positions = append(positions, fileSet.Position(each.Pos()))
		}
		return true
	})
	return positions
}

// A cgo output whose `//line` directive names native.go in a directory that no longer exists parses with every
// position in the package's own native.go, at the line and column the directive gave, the positions of the
// `/*line*/` form after it included.
func TestACgoOutputNamingAGoneDirectoryParsesInThePackagesDirectory(test *testing.T) {
	test.Parallel()

	native := cgoLinePackage(test)
	gone := filepath.Join(test.TempDir(), "gone", "native.go")
	contents := fmt.Appendf(nil, cgoOutputFormat, gone)
	rewritten, isRewritten := rewriteCgoLines(contents, native)
	if !isRewritten {
		test.Fatalf("the directive was left as it is:\n%s", rewritten)
	}
	before, after := positionsOf(test, contents), positionsOf(test, rewritten)
	if len(before) != 3 || len(after) != len(before) {
		test.Fatalf("want three positions each, got %v before and %v after", before, after)
	}
	want := filepath.Join(native.Directory, "native.go")
	for index := range before {
		if before[index].Filename != gone {
			test.Errorf("before the rewrite, position %d names %s, want %s", index, before[index].Filename, gone)
		}
		if after[index].Filename != want {
			test.Errorf("after the rewrite, position %d names %s, want %s", index, after[index], want)
		}
		if after[index].Line != before[index].Line || after[index].Column != before[index].Column {
			test.Errorf("position %d moved from %d:%d to %d:%d", index, before[index].Line, before[index].Column,
				after[index].Line, after[index].Column)
		}
	}
}

// A directive is left as it is, its contents returned unchanged and said to be, when the file it names is no cgo
// file of the package, when it names the package's own directory, when no file of its name is in the package's
// directory, and when the package's cgo file is named in two directories, which would leave which is the package's to
// a guess.
func TestACgoOutputsDirectiveIsLeftAloneUnlessItsRewriteIsExact(test *testing.T) {
	test.Parallel()

	native := cgoLinePackage(test)
	gone := filepath.Join(test.TempDir(), "gone")
	vendored := filepath.Join(test.TempDir(), "vendor", "native.go")
	for _, each := range []struct {
		name     string
		contents []byte
	}{
		{name: "no cgo file of the package",
			contents: fmt.Appendf(nil, cgoOutputFormat, filepath.Join(gone, "other.go"))},
		{name: "the package's own directory",
			contents: fmt.Appendf(nil, cgoOutputFormat, filepath.Join(native.Directory, "native.go"))},
		{name: "two directories",
			contents: fmt.Appendf(nil, cgoOutputFormat+"//line %s:20:1\nvar _ = 0\n",
				filepath.Join(gone, "native.go"), vendored)},
		{name: "a relative file", contents: fmt.Appendf(nil, cgoOutputFormat, "native.go")},
	} {
		rewritten, isRewritten := rewriteCgoLines(each.contents, native)
		if isRewritten || string(rewritten) != string(each.contents) {
			test.Errorf("%s: the directive was rewritten:\n%s", each.name, rewritten)
		}
	}
	missing := &listedPackage{Directory: test.TempDir(), CgoFiles: native.CgoFiles}
	contents := fmt.Appendf(nil, cgoOutputFormat, filepath.Join(gone, "native.go"))
	rewritten, isRewritten := rewriteCgoLines(contents, missing)
	if isRewritten || string(rewritten) != string(contents) {
		test.Errorf("no native.go in the package's directory: the directive was rewritten:\n%s", rewritten)
	}
}
