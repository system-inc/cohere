const formattedSource = "package fixture\n\nvar Count = 1\n"

// unformattedSource differs from gofmt's output on line 5 alone, between lines gofmt leaves alone.
const unformattedSource = "package fixture\n\nvar Count = 1\n\nvar  Total = 2\n\nvar Name = \"fixture\"\n"

// reformattedSource is unformattedSource as gofmt prints it.
const reformattedSource = "package fixture\n\nvar Count = 1\n\nvar Total = 2\n\nvar Name = \"fixture\"\n"

const lastLineSource = "package fixture\n\nvar Count = 1\n\nvar  Total = 2\n"

const noTrailingNewlineSource = "package fixture\n\nvar Count = 1"

const brokenSource = "package fixture\n\nvar Count = \n"

const noPackageClauseSource = "func Add(left, right int) int { return left+right }\n"

const generatedSource = "// Code generated by fixturegen. DO NOT EDIT.\n\npackage fixture\n\nvar  Count = 1\n"

// markerAfterPackageSource holds the generated marker below the package clause, where it does not count.
const markerAfterPackageSource = "package fixture\n\n// Code generated by fixturegen. DO NOT EDIT.\n\nvar  Count = 1\n"

// manyFileCount is enough files that a concurrent run finishes them out of order.
const manyFileCount = 64

// manySources are the kinds of file the many directory cycles through, so every list of a Result has entries.
var manySources = []string{formattedSource, unformattedSource, brokenSource, generatedSource, noPackageClauseSource}

// fixtureDirectory holds every fixture, written once for the package by TestMain. Each test owns the files it
// writes to, in a directory of its own, so the tests run in parallel without seeing each other's writes.
var fixtureDirectory string

func TestMain(suite *testing.M) {
	directory, createError := os.MkdirTemp("", "cohere-go-engine-format-")
	if createError != nil {
		// Ignored: standard error is the only place left to say it, and the test binary exits next.
		fmt.Fprintf(os.Stderr, "creating the fixture directory: %v\n", createError)
		os.Exit(1)
	}
	fixtureDirectory = directory
	if writeError := writeFixtures(); writeError != nil {
		// Ignored: standard error is the only place left to say it, and the test binary exits next.
		fmt.Fprintf(os.Stderr, "writing the fixtures: %v\n", writeError)
		os.Exit(1)
	}
	code := suite.Run()
	if removeError := os.RemoveAll(directory); removeError != nil {
		// Ignored: standard error is the only place left to say it, and the test binary exits next.
		fmt.Fprintf(os.Stderr, "removing the fixture directory: %v\n", removeError)
	}
	os.Exit(code)
}

// writeFixtures writes every fixture under fixtureDirectory.
func writeFixtures() error {
	files := map[string]string{
		"formatted.go":           formattedSource,
		"unformatted.go":         unformattedSource,
		"lastline.go":            lastLineSource,
		"notrailingnewline.go":   noTrailingNewlineSource,
		"broken.go":              brokenSource,
		"nopackageclause.go":     noPackageClauseSource,
		"generated.go":           generatedSource,
		"markerafterpackage.go":  markerAfterPackageSource,
		"write/unformatted.go":   unformattedSource,
		"link/target.go":         unformattedSource,
		"generatedwrite/main.go": generatedSource,
		"brokenwrite/main.go":    brokenSource,
	}
	for index := range manyFileCount {
		files[fmt.Sprintf("many/file%02d.go", index)] = manySources[index%len(manySources)]
	}
	for name, contents := range files {
		path := filepath.Join(fixtureDirectory, filepath.FromSlash(name))
		if makeError := os.MkdirAll(filepath.Dir(path), 0o755); makeError != nil {
			return makeError
		}
		if writeError := os.WriteFile(path, []byte(contents), 0o644); writeError != nil {
			return writeError
		}
	}
	// A mode no temporary file is created with, so a rewrite that kept the temporary file's mode shows.
	if chmodError := os.Chmod(fixturePath("write/unformatted.go"), 0o640); chmodError != nil {
		return chmodError
	}
	return os.Symlink("target.go", fixturePath("link/link.go"))
}

// fixturePath is the absolute path of a fixture named relative to fixtureDirectory.
func fixturePath(name string) string {
	return filepath.Join(fixtureDirectory, filepath.FromSlash(name))
}

// rootOf is the WriteRoot of directory, which a test's writes go under.
func rootOf(test *testing.T, directory string) write_root.WriteRoot {
	test.Helper()
	root, rootError := write_root.New(directory)
	if rootError != nil {
		test.Fatal(rootError)
	}
	return root
}

// fixtureRoot is the WriteRoot of fixtureDirectory, under which every fixture the package's tests write is.
func fixtureRoot(test *testing.T) write_root.WriteRoot {
	test.Helper()
	return rootOf(test, fixtureDirectory)
}

// requireContents fails the test unless the file at path holds contents.
func requireContents(test *testing.T, path, contents string) {
	test.Helper()
	read, readError := os.ReadFile(path)
	if readError != nil {
		test.Fatal(readError)
	}
	if string(read) != contents {
		test.Fatalf("%s holds %q, want %q", path, read, contents)
	}
}

// A file gofmt leaves alone is considered and appears in no list.
func TestAFormattedFileHasNoResult(test *testing.T) {
	test.Parallel()

	result := Run([]string{fixturePath("formatted.go")}, Options{})
	if !reflect.DeepEqual(result, Result{FilesConsidered: 1}) {
		test.Fatalf("a formatted file was reported: %+v", result)
	}
}

// Under a check, an unformatted file is reported at the first line gofmt changes, and not written.
func TestACheckReportsAnUnformattedFileAndWritesNothing(test *testing.T) {
	test.Parallel()

	file := fixturePath("unformatted.go")
	result := Run([]string{file}, Options{})
	want := Result{FilesConsidered: 1, Changed: []ChangedFile{{File: file, Formatted: true, FirstDifferingLine: 5}}}
	if !reflect.DeepEqual(result, want) {
		test.Fatalf("got %+v, want %+v", result, want)
	}
	requireContents(test, file, unformattedSource)
}

// Under a write, an unformatted file is rewritten as gofmt prints it, keeps its mode, and leaves no temporary
// file behind.
func TestAWriteRewritesAnUnformattedFileAndKeepsItsMode(test *testing.T) {
	test.Parallel()

	file := fixturePath("write/unformatted.go")
	result := Run([]string{file}, Options{Write: true, Root: fixtureRoot(test)})
	want := Result{
		FilesConsidered: 1,
		Changed:         []ChangedFile{{File: file, Formatted: true, Written: true, FirstDifferingLine: 5}},
	}
	if !reflect.DeepEqual(result, want) {
		test.Fatalf("got %+v, want %+v", result, want)
	}
	requireContents(test, file, reformattedSource)
	information, statError := os.Stat(file)
	if statError != nil {
		test.Fatal(statError)
	}
	if information.Mode().Perm() != 0o640 {
		test.Fatalf("the rewritten file's mode is %v, want 0640", information.Mode().Perm())
	}
	entries, readError := os.ReadDir(filepath.Dir(file))
	if readError != nil {
		test.Fatal(readError)
	}
	if len(entries) != 1 {
		test.Fatalf("the write left more than the file in its directory: %v", entries)
	}
	if again := Run([]string{file}, Options{}); !reflect.DeepEqual(again, Result{FilesConsidered: 1}) {
		test.Fatalf("the rewritten file is still not formatted: %+v", again)
	}
}

// A write through a symbolic link formats the file it points at and leaves the link a link.
func TestAWriteThroughASymbolicLinkKeepsTheLink(test *testing.T) {
	test.Parallel()

	link := fixturePath("link/link.go")
	result := Run([]string{link}, Options{Write: true, Root: fixtureRoot(test)})
	if len(result.Changed) != 1 || !result.Changed[0].Written {
		test.Fatalf("the linked file was not rewritten: %+v", result)
	}
	information, statError := os.Lstat(link)
	if statError != nil {
		test.Fatal(statError)
	}
	if information.Mode()&os.ModeSymlink == 0 {
		test.Fatalf("the link became a %v", information.Mode())
	}
	requireContents(test, fixturePath("link/target.go"), reformattedSource)
}

// A file that does not parse is not formatted, its reason is gofmt's parse error, and it is left as it was by
// a check and by a write alike.
func TestAFileThatDoesNotParseIsNotFormattedWithTheParseError(test *testing.T) {
	test.Parallel()

	cases := []struct {
		name   string
		file   string
		source string
		write  bool
	}{
		{"a check", "broken.go", brokenSource, false},
		{"a write", "brokenwrite/main.go", brokenSource, true},
		{"no package clause, which format.Source alone would format as a fragment", "nopackageclause.go",
			noPackageClauseSource, true},
	}
	for _, each := range cases {
		test.Run(each.name, func(test *testing.T) {
			test.Parallel()

			_, parseError := parser.ParseFile(token.NewFileSet(), "", each.source, parser.ParseComments)
			if parseError == nil {
				test.Fatal("the fixture parses")
			}
			file := fixturePath(each.file)
			result := Run([]string{file}, Options{Write: each.write, Root: fixtureRoot(test)})
			if result.FilesConsidered != 1 || len(result.Changed) != 0 || len(result.Generated) != 0 ||
				len(result.NotFormatted) != 1 || result.NotFormatted[0].File != file {
				test.Fatalf("the file was not counted as not formatted: %+v", result)
			}
			reason := result.NotFormatted[0].Reason
			if !strings.HasPrefix(reason, "it does not parse: ") || !strings.Contains(reason, parseError.Error()) {
				test.Fatalf("the reason %q does not name the parse error %q", reason, parseError)
			}
			requireContents(test, file, each.source)
		})
	}
}

