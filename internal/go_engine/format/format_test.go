const formattedSource = "package fixture\n\nvar Count = 1\n"

// unformattedSource differs from gofmt's output on line 5 alone, between lines gofmt leaves alone.
const unformattedSource = "package fixture\n\nvar Count = 1\n\nvar  Total = 2\n\nvar Name = \"fixture\"\n"

// reformattedSource is unformattedSource as gofmt prints it.
const reformattedSource = "package fixture\n\nvar Count = 1\n\nvar Total = 2\n\nvar Name = \"fixture\"\n"

const lastLineSource = "package fixture\n\nvar Count = 1\n\nvar  Total = 2\n"

const noTrailingNewlineSource = "package fixture\n\nvar Count = 1"

const brokenSource = "package fixture\n\nvar Count = \n"

const noPackageClauseSource = "func Add(left, right int) int { return left+right }\n"

const generatedSource = "// Code generated by fixturegen. DO NOT EDIT.\n\npackage fixture\n\nvar  Count = 1\n"

// markerAfterPackageSource holds the generated marker below the package clause, where it does not count.
const markerAfterPackageSource = "package fixture\n\n// Code generated by fixturegen. DO NOT EDIT.\n\nvar  Count = 1\n"

// manyFileCount is enough files that a concurrent run finishes them out of order.
const manyFileCount = 64

// manySources are the kinds of file the many directory cycles through, so every list of a Result has entries.
var manySources = []string{formattedSource, unformattedSource, brokenSource, generatedSource, noPackageClauseSource}

// fixtureDirectory holds every fixture, written once for the package by TestMain. Each test owns the files it
// writes to, in a directory of its own, so the tests run in parallel without seeing each other's writes.
var fixtureDirectory string

func TestMain(suite *testing.M) {
	directory, createError := os.MkdirTemp("", "cohere-go-engine-format-")
	if createError != nil {
		// Ignored: standard error is the only place left to say it, and the test binary exits next.
		fmt.Fprintf(os.Stderr, "creating the fixture directory: %v\n", createError)
		os.Exit(1)
	}
	fixtureDirectory = directory
	if writeError := writeFixtures(); writeError != nil {
		// Ignored: standard error is the only place left to say it, and the test binary exits next.
		fmt.Fprintf(os.Stderr, "writing the fixtures: %v\n", writeError)
		os.Exit(1)
	}
	code := suite.Run()
	if removeError := os.RemoveAll(directory); removeError != nil {
		// Ignored: standard error is the only place left to say it, and the test binary exits next.
		fmt.Fprintf(os.Stderr, "removing the fixture directory: %v\n", removeError)
	}
	os.Exit(code)
}

// writeFixtures writes every fixture under fixtureDirectory.
func writeFixtures() error {
	files := map[string]string{
		"formatted.go":           formattedSource,
		"unformatted.go":         unformattedSource,
		"lastline.go":            lastLineSource,
		"notrailingnewline.go":   noTrailingNewlineSource,
		"broken.go":              brokenSource,
		"nopackageclause.go":     noPackageClauseSource,
		"generated.go":           generatedSource,
		"markerafterpackage.go":  markerAfterPackageSource,
		"write/unformatted.go":   unformattedSource,
		"link/target.go":         unformattedSource,
		"generatedwrite/main.go": generatedSource,
		"brokenwrite/main.go":    brokenSource,
	}
	for index := range manyFileCount {
		files[fmt.Sprintf("many/file%02d.go", index)] = manySources[index%len(manySources)]
	}
	for name, contents := range files {
		path := filepath.Join(fixtureDirectory, filepath.FromSlash(name))
		if makeError := os.MkdirAll(filepath.Dir(path), 0o755); makeError != nil {
			return makeError
		}
		if writeError := os.WriteFile(path, []byte(contents), 0o644); writeError != nil {
			return writeError
		}
	}
	// A mode no temporary file is created with, so a rewrite that kept the temporary file's mode shows.
	if chmodError := os.Chmod(fixturePath("write/unformatted.go"), 0o640); chmodError != nil {
		return chmodError
	}
	return os.Symlink("target.go", fixturePath("link/link.go"))
}

// fixturePath is the absolute path of a fixture named relative to fixtureDirectory.
func fixturePath(name string) string {
	return filepath.Join(fixtureDirectory, filepath.FromSlash(name))
}

// requireContents fails the test unless the file at path holds contents.
func requireContents(test *testing.T, path, contents string) {
	test.Helper()
	read, readError := os.ReadFile(path)
	if readError != nil {
		test.Fatal(readError)
	}
	if string(read) != contents {
		test.Fatalf("%s holds %q, want %q", path, read, contents)
	}
}

// A file gofmt leaves alone is considered and appears in no list.
func TestAFormattedFileHasNoResult(test *testing.T) {
	test.Parallel()

	result := Run([]string{fixturePath("formatted.go")}, Options{})
	if !reflect.DeepEqual(result, Result{FilesConsidered: 1}) {
		test.Fatalf("a formatted file was reported: %+v", result)
	}
}

// Under a check, an unformatted file is reported at the first line gofmt changes, and not written.
func TestACheckReportsAnUnformattedFileAndWritesNothing(test *testing.T) {
	test.Parallel()

	file := fixturePath("unformatted.go")
	result := Run([]string{file}, Options{})
	want := Result{FilesConsidered: 1, Changed: []ChangedFile{{File: file, Formatted: true, FirstDifferingLine: 5}}}
	if !reflect.DeepEqual(result, want) {
		test.Fatalf("got %+v, want %+v", result, want)
	}
	requireContents(test, file, unformattedSource)
}

// Under a write, an unformatted file is rewritten as gofmt prints it, keeps its mode, and leaves no temporary
// file behind.
func TestAWriteRewritesAnUnformattedFileAndKeepsItsMode(test *testing.T) {
	test.Parallel()

	file := fixturePath("write/unformatted.go")
	result := Run([]string{file}, Options{Write: true})
	want := Result{
		FilesConsidered: 1,
		Changed:         []ChangedFile{{File: file, Formatted: true, Written: true, FirstDifferingLine: 5}},
	}
	if !reflect.DeepEqual(result, want) {
		test.Fatalf("got %+v, want %+v", result, want)
	}
	requireContents(test, file, reformattedSource)
	information, statError := os.Stat(file)
	if statError != nil {
		test.Fatal(statError)
	}
	if information.Mode().Perm() != 0o640 {
		test.Fatalf("the rewritten file's mode is %v, want 0640", information.Mode().Perm())
	}
	entries, readError := os.ReadDir(filepath.Dir(file))
	if readError != nil {
		test.Fatal(readError)
	}
	if len(entries) != 1 {
		test.Fatalf("the write left more than the file in its directory: %v", entries)
	}
	if again := Run([]string{file}, Options{}); !reflect.DeepEqual(again, Result{FilesConsidered: 1}) {
		test.Fatalf("the rewritten file is still not formatted: %+v", again)
	}
}

// A write through a symbolic link formats the file it points at and leaves the link a link.
func TestAWriteThroughASymbolicLinkKeepsTheLink(test *testing.T) {
	test.Parallel()

	link := fixturePath("link/link.go")
	result := Run([]string{link}, Options{Write: true})
	if len(result.Changed) != 1 || !result.Changed[0].Written {
		test.Fatalf("the linked file was not rewritten: %+v", result)
	}
	information, statError := os.Lstat(link)
	if statError != nil {
		test.Fatal(statError)
	}
	if information.Mode()&os.ModeSymlink == 0 {
		test.Fatalf("the link became a %v", information.Mode())
	}
	requireContents(test, fixturePath("link/target.go"), reformattedSource)
}

// A file that does not parse is not formatted, its reason is gofmt's parse error, and it is left as it was by
// a check and by a write alike.
func TestAFileThatDoesNotParseIsNotFormattedWithTheParseError(test *testing.T) {
	test.Parallel()

	cases := []struct {
		name   string
		file   string
		source string
		write  bool
	}{
		{"a check", "broken.go", brokenSource, false},
		{"a write", "brokenwrite/main.go", brokenSource, true},
		{"no package clause, which format.Source alone would format as a fragment", "nopackageclause.go",
			noPackageClauseSource, true},
	}
	for _, each := range cases {
		test.Run(each.name, func(test *testing.T) {
			test.Parallel()

			_, parseError := parser.ParseFile(token.NewFileSet(), "", each.source, parser.ParseComments)
			if parseError == nil {
				test.Fatal("the fixture parses")
			}
			file := fixturePath(each.file)
			result := Run([]string{file}, Options{Write: each.write})
			if result.FilesConsidered != 1 || len(result.Changed) != 0 || len(result.Generated) != 0 ||
				len(result.NotFormatted) != 1 || result.NotFormatted[0].File != file {
				test.Fatalf("the file was not counted as not formatted: %+v", result)
			}
			reason := result.NotFormatted[0].Reason
			if !strings.HasPrefix(reason, "it does not parse: ") || !strings.Contains(reason, parseError.Error()) {
				test.Fatalf("the reason %q does not name the parse error %q", reason, parseError)
			}
			requireContents(test, file, each.source)
		})
	}
}

// A file that cannot be read is not formatted, and its reason names the read error.
func TestAnUnreadableFileNamesTheReadError(test *testing.T) {
	test.Parallel()

	file := fixturePath("missing.go")
	result := Run([]string{file}, Options{Write: true})
	if len(result.NotFormatted) != 1 || !strings.HasPrefix(result.NotFormatted[0].Reason, "it cannot be read: ") ||
		!strings.Contains(result.NotFormatted[0].Reason, file) {
		test.Fatalf("a missing file was not counted with its read error: %+v", result)
	}
}

// A generated file is skipped and counted however unformatted it is, never reported and never written. The
// marker counts only above the package clause, as go/ast.IsGenerated reads it.
func TestAGeneratedFileIsSkippedAndCounted(test *testing.T) {
	test.Parallel()

	for _, write := range []bool{false, true} {
		file := fixturePath("generated.go")
		if write {
			file = fixturePath("generatedwrite/main.go")
		}
		result := Run([]string{file}, Options{Write: write})
		if !reflect.DeepEqual(result, Result{FilesConsidered: 1, Generated: []string{file}}) {
			test.Fatalf("with write %v, a generated file was not skipped: %+v", write, result)
		}
		requireContents(test, file, generatedSource)
	}

	file := fixturePath("markerafterpackage.go")
	result := Run([]string{file}, Options{})
	want := Result{FilesConsidered: 1, Changed: []ChangedFile{{File: file, Formatted: true, FirstDifferingLine: 5}}}
	if !reflect.DeepEqual(result, want) {
		test.Fatalf("a marker below the package clause skipped the file: got %+v, want %+v", result, want)
	}
}

// The first differing line is a line of the original file, including when the difference is on its last line
// or that line lacks its newline.
func TestTheFirstDifferingLineIsALineOfTheOriginal(test *testing.T) {
	test.Parallel()

	for _, each := range []struct {
		file string
		line int
	}{
		{"lastline.go", 5},
		{"notrailingnewline.go", 3},
	} {
		result := Run([]string{fixturePath(each.file)}, Options{})
		if len(result.Changed) != 1 || result.Changed[0].FirstDifferingLine != each.line {
			test.Fatalf("%s: got %+v, want line %d", each.file, result, each.line)
		}
	}

	cases := []struct {
		name      string
		original  string
		formatted string
		line      int
	}{
		{"the last line differs", "a\nb\nc  \n", "a\nb\nc\n", 3},
		{"the last line lacks its newline", "a\nb", "a\nb\n", 2},
		{"a blank line dropped at the end", "a\n\n\n", "a\n", 2},
		{"a carriage return on every line", "a\r\nb\r\n", "a\nb\n", 1},
		{"a line added after the last", "a\n", "a\nb\n", 1},
	}
	for _, each := range cases {
		test.Run(each.name, func(test *testing.T) {
			test.Parallel()

			if line := firstDifferingLine([]byte(each.original), []byte(each.formatted)); line != each.line {
				test.Fatalf("got line %d, want %d", line, each.line)
			}
		})
	}
}

// Many files come back in the order they were given, the same on every concurrent run and on a
// single-threaded one, with every file accounted for.
func TestManyFilesComeBackInTheOrderGiven(test *testing.T) {
	test.Parallel()

	// Reversed, so an answer sorted by name would not pass for one in input order.
	var files []string
	for index := manyFileCount - 1; index >= 0; index-- {
		files = append(files, fixturePath(fmt.Sprintf("many/file%02d.go", index)))
	}
	var want Result
	want.FilesConsidered = len(files)
	for _, file := range files {
		contents, readError := os.ReadFile(file)
		if readError != nil {
			test.Fatal(readError)
		}
		switch string(contents) {
		case unformattedSource:
			want.Changed = append(want.Changed, ChangedFile{File: file, Formatted: true, FirstDifferingLine: 5})
		case brokenSource, noPackageClauseSource:
			want.NotFormatted = append(want.NotFormatted, NotFormattedFile{File: file})
		case generatedSource:
			want.Generated = append(want.Generated, file)
		}
	}

	runs := []Options{{}, {}, {}, {SingleThreaded: true}}
	var first Result
	for index, options := range runs {
		result := Run(files, options)
		notFormattedFiles := make([]NotFormattedFile, 0, len(result.NotFormatted))
		for _, each := range result.NotFormatted {
			if each.Reason == "" {
				test.Fatalf("%s was not formatted with no reason", each.File)
			}
			notFormattedFiles = append(notFormattedFiles, NotFormattedFile{File: each.File})
		}
		withoutReasons := result
		withoutReasons.NotFormatted = notFormattedFiles
		if !reflect.DeepEqual(withoutReasons, want) {
			test.Fatalf("run %d (%+v): got %+v, want %+v", index, options, withoutReasons, want)
		}
		if index == 0 {
			first = result
		} else if !reflect.DeepEqual(result, first) {
			test.Fatalf("run %d (%+v) differs from the first: %+v, then %+v", index, options, first, result)
		}
	}
	for index := range manyFileCount {
		requireContents(test, fixturePath(fmt.Sprintf("many/file%02d.go", index)), manySources[index%len(manySources)])
	}
}

// A file gofmt left as it was, or skipped as generated, is known by its bytes: a later run with the verdicts answers
// it without formatting it, and the same Result comes back. A file whose bytes change is formatted again, so an edit
// that unformats it is reported, never answered from what was known of the file before.
func TestKnownFilesAnswerTheSameBytesAndOnlyThem(test *testing.T) {
	test.Parallel()

	directory := test.TempDir()
	clean := filepath.Join(directory, "clean.go")
	generated := filepath.Join(directory, "generated.go")
	edited := filepath.Join(directory, "edited.go")
	// Each file's bytes are its own, since a run that meets the same bytes twice knows the second already.
	for file, source := range map[string]string{clean: formattedSource, generated: generatedSource,
		edited: reformattedSource} {
		if writeError := os.WriteFile(file, []byte(source), 0o644); writeError != nil {
			test.Fatalf("writing %s: %v", file, writeError)
		}
	}
	files := []string{clean, generated, edited}
	first := DecodeKnownFiles(nil)
	learned := Run(files, Options{Known: first})
	if learned.Known != 0 || len(learned.Generated) != 1 || len(learned.Changed) != 0 {
		test.Fatalf("want nothing known yet, the generated file skipped and nothing changed, got %+v", learned)
	}
	encoded, encodeError := first.Encode()
	if encodeError != nil {
		test.Fatalf("encoding the verdicts: %v", encodeError)
	}

	answered := Run(files, Options{Known: DecodeKnownFiles(encoded)})
	if answered.Known != 3 {
		test.Fatalf("want every file known by its bytes, got %+v", answered)
	}
	answered.Known = 0
	if !reflect.DeepEqual(answered, learned) {
		test.Fatalf("known\n%+v\nformatted\n%+v", answered, learned)
	}

	if writeError := os.WriteFile(edited, []byte(unformattedSource), 0o644); writeError != nil {
		test.Fatalf("unformatting %s: %v", edited, writeError)
	}
	afterEdit := Run(files, Options{Known: DecodeKnownFiles(encoded)})
	want := []ChangedFile{{File: edited, Formatted: true, FirstDifferingLine: 5}}
	if afterEdit.Known != 2 || !reflect.DeepEqual(afterEdit.Changed, want) {
		test.Fatalf("want the edited file formatted again and reported at line 5, got %+v", afterEdit)
	}
}

// callSource is formatted, and callWrapped is the same program with its call broken one argument per line, gofmt's
// own layout of it, which a wrap may write in its place.
const (
	callSource  = "package fixture\n\nvar Values = Pair(1, 2)\n"
	callWrapped = "package fixture\n\nvar Values = Pair(\n\t1,\n\t2,\n)\n"
)

// wrapTo is an Options.Wrap that answers every file with output, claiming one line brought within the limit, and
// counts how often it was asked.
func wrapTo(output string, asked *atomic.Int32) func([]byte) Wrapping {
	return func([]byte) Wrapping {
		asked.Add(1)
		return Wrapping{Output: []byte(output), Lines: 1}
	}
}

// writeFile writes contents to a file of its own in a fresh directory and returns its path.
func writeFile(test *testing.T, contents string) string {
	test.Helper()
	file := filepath.Join(test.TempDir(), "file.go")
	if writeError := os.WriteFile(file, []byte(contents), 0o644); writeError != nil {
		test.Fatalf("writing %s: %v", file, writeError)
	}
	return file
}

// A write keeps a wrap that is the same program and gofmt's own layout, as a change gofmt did not make, counted by
// the lines it wrapped. A check never asks the wrap, since long lines are the lint phase's to report.
func TestAWriteKeepsAnEquivalentWrapAndACheckNeverAsks(test *testing.T) {
	test.Parallel()

	var asked atomic.Int32
	file := writeFile(test, callSource)
	if checked := Run([]string{file}, Options{Wrap: wrapTo(callWrapped, &asked)}); asked.Load() != 0 ||
		!reflect.DeepEqual(checked, Result{FilesConsidered: 1}) {
		test.Fatalf("a check asked the wrap %d times and got %+v", asked.Load(), checked)
	}
	result := Run([]string{file}, Options{Write: true, Wrap: wrapTo(callWrapped, &asked)})
	want := Result{
		FilesConsidered: 1,
		Changed:         []ChangedFile{{File: file, WrappedLines: 1, Written: true, FirstDifferingLine: 3}},
	}
	if !reflect.DeepEqual(result, want) {
		test.Fatalf("got %+v, want %+v", result, want)
	}
	requireContents(test, file, callWrapped)
}

// A wrap that is not the same program, or that gofmt would lay out again, is declined with why: the file holds gofmt's
// output, and the run names it. Without the two checks the fix phase would write whatever a wrap returned.
func TestAWriteDeclinesAWrapThatIsNotTheSameProgramOrNotGofmts(test *testing.T) {
	test.Parallel()

	for _, testCase := range []struct {
		name   string
		output string
		reason string
	}{
		{"an argument changed", "package fixture\n\nvar Values = Pair(\n\t1,\n\t3,\n)\n", "not the same program"},
		{"a layout gofmt changes", "package fixture\n\nvar  Values = Pair(\n\t1,\n\t2,\n)\n", "gofmt would change"},
	} {
		test.Run(testCase.name, func(test *testing.T) {
			test.Parallel()

			var asked atomic.Int32
			file := writeFile(test, callSource)
			result := Run([]string{file}, Options{Write: true, Wrap: wrapTo(testCase.output, &asked)})
			if len(result.Changed) != 0 || len(result.WrapDeclined) != 1 || result.WrapDeclined[0].File != file ||
				!strings.Contains(result.WrapDeclined[0].Reason, testCase.reason) {
				test.Fatalf("want the wrap declined as %q, got %+v", testCase.reason, result)
			}
			requireContents(test, file, callSource)
		})
	}
}

// gofmt's verdict that a file is formatted, kept by a run that did not wrap, is not trusted by a run that wraps: the
// file may hold a long line, so the run asks the wrap, and keeps what the wrap says. A verdict the wrap gave is
// trusted by both. A declined wrap is never known, so the next run asks again and says again why.
func TestAVerdictWithoutTheWrapIsNotTrustedByARunThatWraps(test *testing.T) {
	test.Parallel()

	var asked atomic.Int32
	file := writeFile(test, callSource)
	gofmtOnly := DecodeKnownFiles(nil)
	if learned := Run([]string{file}, Options{Known: gofmtOnly}); learned.Known != 0 {
		test.Fatalf("want nothing known yet, got %+v", learned)
	}
	encoded, encodeError := gofmtOnly.Encode()
	if encodeError != nil {
		test.Fatalf("encoding the verdicts: %v", encodeError)
	}
	if again := Run([]string{file}, Options{Known: DecodeKnownFiles(encoded)}); again.Known != 1 {
		test.Fatalf("want gofmt's verdict trusted by a run that does not wrap, got %+v", again)
	}

	wrapped := Run([]string{file}, Options{Write: true, Known: DecodeKnownFiles(encoded),
		Wrap: wrapTo(callWrapped, &asked)})
	if wrapped.Known != 0 || len(wrapped.Changed) != 1 || wrapped.Changed[0].WrappedLines != 1 {
		test.Fatalf("want gofmt's verdict read past and the file wrapped, got %+v", wrapped)
	}
	requireContents(test, file, callWrapped)

	fits := DecodeKnownFiles(nil)
	nothingToDo := func([]byte) Wrapping { return Wrapping{} }
	Run([]string{file}, Options{Write: true, Known: fits, Wrap: nothingToDo})
	encoded, encodeError = fits.Encode()
	if encodeError != nil {
		test.Fatalf("encoding the verdicts: %v", encodeError)
	}
	for _, options := range []Options{{Write: true, Wrap: nothingToDo}, {}} {
		options.Known = DecodeKnownFiles(encoded)
		if known := Run([]string{file}, options); known.Known != 1 {
			test.Fatalf("want the wrap's verdict trusted with %+v, got %+v", options, known)
		}
	}

	declines := DecodeKnownFiles(nil)
	declining := func([]byte) Wrapping { return Wrapping{Declined: "a planted refusal"} }
	Run([]string{file}, Options{Write: true, Known: declines, Wrap: declining})
	encoded, encodeError = declines.Encode()
	if encodeError != nil {
		test.Fatalf("encoding the verdicts: %v", encodeError)
	}
	again := Run([]string{file}, Options{Write: true, Known: DecodeKnownFiles(encoded), Wrap: declining})
	if again.Known != 0 || len(again.WrapDeclined) != 1 {
		test.Fatalf("want a declined wrap tried and named again, got %+v", again)
	}
}
