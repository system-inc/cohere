// randomFunctionNames are randomFunctions' keys, sorted, which staticcheck_code.CallIndex compares a call's name with
// in place, so the name is never built for a call that is none of them.
var randomFunctionNames = slices.Sorted(maps.Keys(randomFunctions))

// Check judges binary, under ancestors, outermost first: one of an operator for which identical operands are a
// mistake, not of floats, whose two operands are of one syntax kind and print the same, is reported, but for cgo's
// `0 == 0` in a generated file and two calls of one random function.
func Check(context *rule.Context, binary *ast.BinaryExpr, ancestors []ast.Node) {
	switch binary.Op {
	case token.EQL, token.NEQ:
		if isComparableAssertion(ancestors, binary) {
			return
		}
	case token.SUB, token.QUO, token.AND, token.REM, token.OR, token.XOR, token.AND_NOT,
		token.LAND, token.LOR, token.LSS, token.GTR, token.LEQ, token.GEQ:
	default:
		// For some operators, such as + and *, identical operands make sense.
		return
	}
	// A float can differ from itself, NaN does, so floats are left alone for every operator.
	if type_predicates.MayHoldFloat(context.TypesInfo.TypeOf(binary.X)) {
		return
	}
	if reflect.TypeOf(binary.X) != reflect.TypeOf(binary.Y) {
		return
	}
	if staticcheck_report.Render(context, binary.X) != staticcheck_report.Render(context, binary.Y) {
		return
	}
	if isGeneratedZeroComparison(context, binary) {
		return
	}
	if call, isCall := binary.X.(*ast.CallExpr); isCall &&
		staticcheck_code.CallIndex(context, call, randomFunctionNames...) >= 0 {
		return
	}
	staticcheck_report.Report(context, binary,
		fmt.Sprintf("identical expressions on the left and right side of the '%s' operator", binary.Op))
}

// isComparableAssertion is whether binary, under ancestors, compares two empty composite literals as the whole value
// given to a blank variable, `var _ = T{} == T{}`, which asserts at compile time that T is comparable.
func isComparableAssertion(ancestors []ast.Node, binary *ast.BinaryExpr) bool {
	if literal, isLiteral := binary.X.(*ast.CompositeLit); !isLiteral || len(literal.Elts) != 0 {
		return false
	}
	if literal, isLiteral := binary.Y.(*ast.CompositeLit); !isLiteral || len(literal.Elts) != 0 {
		return false
	}
	if len(ancestors) == 0 {
		return false
	}
	// Parentheses around the comparison are not looked through, as the original does not.
	specification, isValue := ancestors[len(ancestors)-1].(*ast.ValueSpec)
	if !isValue {
		return false
	}
	// The original asks the cursor whether binary sits in the declaration's Values and at what index, which is
	// binary's own place among them.
	index := slices.Index(specification.Values, ast.Expr(binary))
	if index < 0 {
		return false
	}
	return specification.Names[index].Name == "_"
}

// isGeneratedZeroComparison is whether binary is `0 == 0`, or any operator between two literal zeros, in a file
// staticcheck judges generated, as cgo writes `0 == 0` for true in case the code shadowed true. The file is the one
// the literal was parsed from, its line directives ignored, as the original asks.
func isGeneratedZeroComparison(context *rule.Context, binary *ast.BinaryExpr) bool {
	left, isLeftLiteral := binary.X.(*ast.BasicLit)
	right, isRightLiteral := binary.Y.(*ast.BasicLit)
	if !isLeftLiteral || !isRightLiteral || left.Kind != token.INT || right.Kind != token.INT {
		return false
	}
	if left.Value != "0" || right.Value != "0" {
		return false
	}
	return context.IsGenerated(context.FileSet.PositionFor(left.Pos(), false).Filename)
}
