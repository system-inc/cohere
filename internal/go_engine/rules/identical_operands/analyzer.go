// Package identical_operands is staticcheck's SA4000, a binary expression whose two operands are the same, such as
// `a == a` or `x - x`, which is almost always a typo for another operand, ported as a check on syntax that reports
// through the kit every port of staticcheck shares.
//
// It is translated, not copied, from honnef.co/go/tools@v0.8.1 staticcheck/sa4000/sa4000.go, whose logic it keeps and
// whose message it reports word for word, over the whole binary expression, where staticcheck's report puts it. It
// tells two operands the same by printing both with staticcheck_report.Render, names a call with
// staticcheck_code.CallIndex, asks the context's IsGenerated by the name of the file a literal was parsed from where
// the original asks code.IsGenerated, and reports through staticcheck_report.Report, each the port of the one the
// original calls, proven against it beside it. It reads a type's set of types through staticcheck's
// go/types/typeutil, as the original does, and reads the parent the original's code.Cursor reads from the ancestors
// the dispatcher hands. Like the original, it judges operands by their printed text alone, so `f() == f()` is
// reported even when f has effects, and only math/rand's random functions are spared that (upstream's fn2 shows
// them). The registry runs the port in the original's place, under its name, and the original stays only as the
// oracle: the parity tests beside this file run both over the same packages, and the two differ nowhere they hold.
package identical_operands

import (
	"fmt"
	"go/ast"
	"go/token"
	"maps"
	"reflect"
	"slices"

	"github.com/system-inc/cohere/internal/go_engine/rule"
	"github.com/system-inc/cohere/internal/go_engine/rules/dispatch"
	"github.com/system-inc/cohere/internal/go_engine/rules/staticcheck_code"
	"github.com/system-inc/cohere/internal/go_engine/rules/staticcheck_report"
	"github.com/system-inc/cohere/internal/go_engine/type_predicates"
)

// Listener is what the port hears of each package from the dispatcher: every binary expression, in preorder, with its
// ancestors, whose last is the expression's parent.
var Listener = rule.Listener{
	FileLocal: true,
	Nodes:     []ast.Node{(*ast.BinaryExpr)(nil)},
	Node: func(context *rule.Context, node ast.Node, stack []ast.Node) {
		binary, isBinary := node.(*ast.BinaryExpr)
		if !isBinary {
			// Invariant: the dispatcher hands Node only the binary expressions it was asked for.
			panic("identical_operands: the dispatcher handed over a node that is not a binary expression")
		}
		Check(context, binary, stack)
	},
}

// Analyzer is the rule's own analyzer, reporting what the dispatcher's walk found for Listener under the original's
// name, so the rule, its settings and every `//cohere:ignore` naming it read the same once the port takes the
// original's place.
var Analyzer = dispatch.RuleAnalyzer(
	rule.Namespace+"SA4000",
	"SA4000",
	"Flags a binary expression whose two operands are identical: staticcheck's SA4000, ported as a check on "+
		"syntax.",
	&Listener,
)

