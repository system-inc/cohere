package rules

// staticcheckCheck is what the registry reads of one of staticcheck's checks: its code, whether staticcheck leaves it
// off by default (its documentation's NonDefault), and whether its findings across builds merge only when every
// build makes them (its documentation's MergeIf, lint.MergeIfAll). The registry keeps these in tables of its own rather
// than walking staticcheck's suites, since a suite's package imports every original check, and through them
// staticcheck's intermediate representation, which the binary then carried though no rule runs it (#7cv09fg).
// TestTheStaticcheckTablesAreTheSuites holds each table to its suites entry for entry and field for field, so a
// staticcheck release that adds, drops or reorders a check, or changes either field, fails there by name.
type staticcheckCheck struct {
	name       string
	nonDefault bool
	mergeIfAll bool
}

