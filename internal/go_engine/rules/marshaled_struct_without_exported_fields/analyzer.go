// Package marshaled_struct_without_exported_fields is staticcheck's SA9005, a struct given to encoding/json or
// encoding/xml to marshal or unmarshal that has fields, none of them exported, and no method of its own to marshal it,
// so the package reads or writes nothing of it, ported onto staticcheck_call, the house's translation of the callcheck
// framework the original rides.
//
// It is translated, not copied, from honnef.co/go/tools@v0.8.1 staticcheck/sa9005/sa9005.go, whose rules it keeps
// and whose message it reports word for word over the same range, the value argument's expression. It finds each
// value's position in staticcheck's knowledge package, a table of standard library argument positions that the house
// ports in a later wave. Like the original, it judges nothing in a generated file, which may hold empty structs
// generated from data models, asking the context's IsGenerated by the name of the file a call was parsed from, as
// the original asks, and not by the name a line directive moves it to. The registry runs the port in the original's
// place, under its name, and the original stays only as the oracle: the parity tests beside this file run both over
// staticcheck's own fixture and the house's. The two differ nowhere: staticcheck_call departs from callcheck only on
// calls these functions are never part of, as testdata/differences records.
package marshaled_struct_without_exported_fields

import (
	"fmt"
	"go/types"

	"honnef.co/go/tools/go/types/typeutil"
	"honnef.co/go/tools/knowledge"

	"github.com/system-inc/cohere/internal/go_engine/rule"
	"github.com/system-inc/cohere/internal/go_engine/rules/dispatch"
	"github.com/system-inc/cohere/internal/go_engine/rules/staticcheck_call"
)

// Check judges every call in a function to one of encoding/json's or encoding/xml's functions that marshal or
// unmarshal a value, each with the methods that marshal its format.
var Check = staticcheck_call.FunctionCheck(map[string]staticcheck_call.Rule{
	// The original doubts flagging XML, since an empty struct marshals to its type name, and leaves gob unjudged; the
	// port keeps both choices.
	"encoding/json.Marshal":           checkValue("json.Marshal.v", "MarshalJSON", "MarshalText"),
	"encoding/json.MarshalIndent":     checkValue("json.MarshalIndent.v", "MarshalJSON", "MarshalText"),
	"encoding/xml.Marshal":            checkValue("xml.Marshal.v", "MarshalXML", "MarshalText"),
	"encoding/xml.MarshalIndent":      checkValue("xml.MarshalIndent.v", "MarshalXML", "MarshalText"),
	"(*encoding/json.Encoder).Encode": checkValue("(*encoding/json.Encoder).Encode.v", "MarshalJSON", "MarshalText"),
	"(*encoding/xml.Encoder).Encode":  checkValue("(*encoding/xml.Encoder).Encode.v", "MarshalXML", "MarshalText"),

	"encoding/json.Unmarshal":         checkValue("json.Unmarshal.v", "UnmarshalJSON", "UnmarshalText"),
	"encoding/xml.Unmarshal":          checkValue("xml.Unmarshal.v", "UnmarshalXML", "UnmarshalText"),
	"(*encoding/json.Decoder).Decode": checkValue("(*encoding/json.Decoder).Decode.v", "UnmarshalJSON", "UnmarshalText"),
	"(*encoding/xml.Decoder).Decode":  checkValue("(*encoding/xml.Decoder).Decode.v", "UnmarshalXML", "UnmarshalText"),
})

// Listener is what the port hears of each package from the dispatcher: every function, each judged on its own.
var Listener = rule.Listener{Function: Check}

// Analyzer is the rule's own analyzer, reporting what the dispatcher's walk found for Listener under the original's
// name, so the rule, its settings and every `//cohere:ignore` naming it read the same once the port takes the
// original's place.
var Analyzer = dispatch.RuleAnalyzer(
	rule.Namespace+"SA9005",
	"SA9005",
	"Flags a struct given to encoding/json or encoding/xml that has fields, none exported, and no method to "+
		"marshal it: staticcheck's SA9005, ported onto staticcheck's intermediate representation.",
	&Listener,
)

// checkValue is the rule that marks the value, the argument knowledge names argument, a struct or a pointer to one,
// when the struct has fields, none of them exported, its embedded structs' fields counted as its own, and the
// value's type has none of methods.
func checkValue(argument string, methods ...string) staticcheck_call.Rule {
	position := knowledge.Arg(argument)
	return func(call *staticcheck_call.Call) {
		// The original asks by the name of the file the call was parsed from, so a generated file whose line
		// directives point into another Go file is still judged generated, and a file pointing into a generated one
		// is not.
		parsed := call.Context.Fset.PositionFor(call.Instruction.Pos(), false)
		if call.Context.IsGenerated(parsed.Filename) {
			return
		}
		value := call.Arguments[position]
		valueType := value.Value.Type()
		structure, isStructure := typeutil.Dereference(valueType).Underlying().(*types.Struct)
		if !isStructure || structure.NumFields() == 0 {
			return
		}
		for _, field := range typeutil.FlattenFields(structure) {
			if field.Var.Exported() {
				return
			}
		}
		// The method set is of the value's own type, so a method on a pointer receiver counts only for a pointer.
		// The methods' signatures are not checked, as the original does not, which vet's own check covers.
		methodSet := call.Instruction.Parent().Prog.MethodSets.MethodSet(valueType)
		for _, method := range methods {
			if methodSet.Lookup(nil, method) != nil {
				return
			}
		}
		value.Invalid(fmt.Sprintf("struct type '%s' doesn't have any exported fields, nor custom marshaling",
			typeutil.Dereference(valueType)))
	}
}
