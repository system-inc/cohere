import Foundation

/*
 An Xcode project as its project file describes it: its native targets, which Swift files each compiles, the
 Swift version and SDK each names, and the local packages it links. The counterpart of `PackageModel` for a
 project SwiftPM cannot describe.

 Read from `project.pbxproj` itself, with Apple's own property list parser, which reads the old-style format
 the file is written in. A project generated by xcodegen is read from what xcodegen wrote, never from its spec,
 because the project file is what Xcode builds: restating xcodegen's glob rules here would be a second answer
 that drifts from the first.

 A file belongs to a target the way Xcode decides it. A file reference in the target's sources phase is one,
 its path resolved through its source tree and the groups above it. A synchronized folder (Xcode 16) is every
 Swift file under it on disk, less the files an exception set takes out of this target.

 A project file this reader cannot follow is a failure, never an empty answer. An empty target list would
 leave every file unchecked, and a run over nothing reads clean.
 */
public struct XcodeProjectFile: Equatable, Sendable {
    /* One native target. Aggregate and legacy targets compile nothing of their own and are not listed. */
    public struct Target: Equatable, Sendable {
        public var name: String
        /* Xcode's product type, as written: `com.apple.product-type.application`, `...framework`, `...bundle.unit-test`. */
        public var productType: String
        /* Every .swift file the target compiles, absolute, standardized, symlinks resolved, sorted. */
        public var sources: [URL]
        /* `SWIFT_VERSION` as the target's own build settings write it, else the project's, else nil. */
        public var swiftVersion: String?
        /* `SDKROOT` the same way (`iphoneos`, `macosx`): the platform a build of the target is for. */
        public var sdkRoot: String?

        public init(name: String, productType: String, sources: [URL], swiftVersion: String?, sdkRoot: String?) {
            self.name = name
            self.productType = productType
            self.sources = sources
            self.swiftVersion = swiftVersion
            self.sdkRoot = sdkRoot
        }
    }

    /* The project file could not be read as a project, so nothing in it can be checked. */
    public struct ReadFailure: Error, CustomStringConvertible {
        public var description: String
    }

    /* The directory the project's `SOURCE_ROOT` names: the .xcodeproj's parent joined with PBXProject's `projectDirPath`. */
    public var sourceRoot: URL
    /* Sorted by name. */
    public var targets: [Target]
    /*
     The directories of the local Swift packages the project links, standardized, symlinks resolved, sorted: each
     package reference's path, and each file reference to a folder holding a `Package.swift`, which is how xcodegen
     and older Xcode point at one. What a build reads beyond the project's own folder.
     */
    public var localPackages: [URL]

    /* `projectBundle` is the .xcodeproj directory. */
    public static func read(_ projectBundle: URL) throws -> XcodeProjectFile {
        let projectFile = projectBundle.appendingPathComponent("project.pbxproj")
        let data: Data
        do {
            data = try Data(contentsOf: projectFile)
        }
        catch {
            throw ProjectObjects.failure(projectFile, "it could not be opened (\(error.localizedDescription))")
        }
        let propertyList: Any
        do {
            /*
             Unsafe because the `format` parameter is a pointer the parser may write through; correct because nil is
             passed, so it writes nothing.
             */
            propertyList = try unsafe PropertyListSerialization.propertyList(from: data, options: [], format: nil)
        }
        catch {
            throw ProjectObjects.failure(projectFile, "it is not a property list")
        }
        guard let top = propertyList as? [String: Any] else {
            throw ProjectObjects.failure(projectFile, "it is a property list, but not a dictionary")
        }
        guard let rootObject = top["rootObject"] as? String else {
            throw ProjectObjects.failure(projectFile, "it names no rootObject")
        }
        guard let objects = top["objects"] as? [String: Any] else {
            throw ProjectObjects.failure(projectFile, "it holds no objects dictionary")
        }
        let project = try ProjectObjects(projectFile: projectFile, objects: objects, rootObject: rootObject)
        return XcodeProjectFile(
            sourceRoot: project.sourceRoot,
            targets: try project.targets(),
            localPackages: try project.localPackages(),
        )
    }
}

/*
 The project file's object table, and the walks over it. Every object is a dictionary keyed by an identifier,
 and every reference between objects is an identifier, so each read checks the shape it relies on and fails
 with a sentence naming what was missing.
 */
private struct ProjectObjects {
    var projectFile: URL
    var objects: [String: [String: Any]]
    var project: [String: Any]
    var sourceRoot: URL
    var mainGroup: String
    /* Each group's or file's containing group, from every group's `children`. */
    var parents: [String: String]

    init(projectFile: URL, objects: [String: Any], rootObject: String) throws {
        self.projectFile = projectFile
        var table: [String: [String: Any]] = [:]
        for (identifier, object) in objects {
            guard let dictionary = object as? [String: Any] else {
                throw Self.failure(projectFile, "object \(identifier) is not a dictionary")
            }
            table[identifier] = dictionary
        }
        self.objects = table
        guard let project = table[rootObject], project["isa"] as? String == "PBXProject" else {
            throw Self.failure(projectFile, "its rootObject \(rootObject) is not a PBXProject")
        }
        self.project = project
        guard let mainGroup = project["mainGroup"] as? String else {
            throw Self.failure(projectFile, "its PBXProject names no mainGroup")
        }
        self.mainGroup = mainGroup
        /* An empty `projectDirPath`, which is what xcodegen and Xcode write, leaves the root where the bundle sits. */
        let bundleParent = projectFile.deletingLastPathComponent().deletingLastPathComponent()
        let projectDirectoryPath = project["projectDirPath"] as? String ?? ""
        let sourceRoot =
            projectDirectoryPath.hasPrefix("/")
            ? URL(fileURLWithPath: projectDirectoryPath, isDirectory: true)
            : bundleParent.appendingPathComponent(projectDirectoryPath, isDirectory: true)
        self.sourceRoot = sourceRoot.standardizedFileURL.resolvingSymlinksInPath()
        var parents: [String: String] = [:]
        for (identifier, object) in table where object["children"] != nil {
            guard let children = object["children"] as? [String] else {
                throw Self.failure(projectFile, "group \(identifier) has children that are not a list of identifiers")
            }
            for child in children {
                parents[child] = identifier
            }
        }
        self.parents = parents
    }

    static func failure(_ projectFile: URL, _ problem: String) -> XcodeProjectFile.ReadFailure {
        XcodeProjectFile.ReadFailure(
            description:
                "The Xcode project file \(projectFile.path) could not be read, so no target's files are known and nothing in it was checked: \(problem)."
        )
    }

    func failure(_ problem: String) -> XcodeProjectFile.ReadFailure {
        Self.failure(projectFile, problem)
    }

    func object(_ identifier: String, as role: String) throws -> [String: Any] {
        guard let object = objects[identifier] else {
            throw failure("\(identifier), the \(role), is not among its objects")
        }
        return object
    }

    func identifiers(_ key: String, of object: [String: Any], _ owner: String) throws -> [String] {
        guard let value = object[key] else { return [] }
        guard let identifiers = value as? [String] else {
            throw failure("the \(key) of \(owner) is not a list of identifiers")
        }
        return identifiers
    }

    func targets() throws -> [XcodeProjectFile.Target] {
        guard let targetIdentifiers = project["targets"] as? [String] else {
            throw failure("its PBXProject has no list of targets")
        }
        let projectSwiftVersion = try setting("SWIFT_VERSION", configurationList: project["buildConfigurationList"])
        let projectSdkRoot = try setting("SDKROOT", configurationList: project["buildConfigurationList"])
        var targets: [XcodeProjectFile.Target] = []
        for targetIdentifier in targetIdentifiers {
            let target = try object(targetIdentifier, as: "target")
            guard target["isa"] as? String == "PBXNativeTarget" else { continue }
            guard let name = target["name"] as? String, let productType = target["productType"] as? String else {
                throw failure("target \(targetIdentifier) has no name or no productType")
            }
            var sources = Set<URL>()
            for phaseIdentifier in try identifiers("buildPhases", of: target, "target \(name)") {
                let phase = try object(phaseIdentifier, as: "build phase of target \(name)")
                guard phase["isa"] as? String == "PBXSourcesBuildPhase" else { continue }
                for buildFileIdentifier in try identifiers("files", of: phase, "the sources phase of target \(name)") {
                    if let source = try buildFileSource(buildFileIdentifier, targetName: name) {
                        sources.insert(source)
                    }
                }
            }
            let synchronizedGroups = try identifiers("fileSystemSynchronizedGroups", of: target, "target \(name)")
            for groupIdentifier in synchronizedGroups {
                sources.formUnion(
                    try synchronizedSources(groupIdentifier, targetIdentifier: targetIdentifier, targetName: name)
                )
            }
            targets.append(
                XcodeProjectFile.Target(
                    name: name,
                    productType: productType,
                    sources: sources.sorted { $0.path < $1.path },
                    swiftVersion: try setting("SWIFT_VERSION", configurationList: target["buildConfigurationList"])
                        ?? projectSwiftVersion,
                    sdkRoot: try setting("SDKROOT", configurationList: target["buildConfigurationList"])
                        ?? projectSdkRoot,
                )
            )
        }
        return targets.sorted { $0.name < $1.name }
    }

    /*
     The Swift file a sources phase entry compiles, or nil when it is not one. A package product
     (`productRef` and no `fileRef`) and a variant group (a localized resource) are not Swift sources, and
     neither is a file in a tree that is not ours, such as the SDK or the build products.
     */
    func buildFileSource(_ buildFileIdentifier: String, targetName: String) throws -> URL? {
        let buildFile = try object(buildFileIdentifier, as: "build file of target \(targetName)")
        guard let fileIdentifier = buildFile["fileRef"] as? String else {
            guard buildFile["productRef"] != nil else {
                throw failure(
                    "build file \(buildFileIdentifier) of target \(targetName) names neither a fileRef nor a productRef"
                )
            }
            return nil
        }
        let file = try object(fileIdentifier, as: "file of build file \(buildFileIdentifier)")
        guard file["isa"] as? String == "PBXFileReference" else { return nil }
        guard let path = file["path"] as? String else {
            throw failure("file reference \(fileIdentifier) has no path")
        }
        guard path.hasSuffix(".swift"), let location = try resolvedLocation(fileIdentifier) else { return nil }
        return location.resolvingSymlinksInPath()
    }

    /*
     Every Swift file under a synchronized folder, less this target's membership exceptions, which are paths
     relative to the folder and may name a folder whose files all leave. Hidden files and directories are not
     walked: Xcode does not show them, and a `.build` inside the folder would cost a walk of thousands.
     */
    func synchronizedSources(_ groupIdentifier: String, targetIdentifier: String, targetName: String) throws -> [URL] {
        let group = try object(groupIdentifier, as: "synchronized folder of target \(targetName)")
        guard group["isa"] as? String == "PBXFileSystemSynchronizedRootGroup" else {
            throw failure(
                "synchronized folder \(groupIdentifier) of target \(targetName) is not a PBXFileSystemSynchronizedRootGroup"
            )
        }
        guard let folder = try resolvedLocation(groupIdentifier)?.resolvingSymlinksInPath() else { return [] }
        var exceptions: Set<String> = []
        for exceptionIdentifier in try identifiers("exceptions", of: group, "synchronized folder \(groupIdentifier)") {
            let exceptionSet = try object(
                exceptionIdentifier,
                as: "exception set of synchronized folder \(groupIdentifier)",
            )
            guard exceptionSet["isa"] as? String == "PBXFileSystemSynchronizedBuildFileExceptionSet",
                exceptionSet["target"] as? String == targetIdentifier
            else { continue }
            exceptions.formUnion(
                try identifiers("membershipExceptions", of: exceptionSet, "exception set \(exceptionIdentifier)")
            )
        }
        guard let walker = FileManager.default.enumerator(atPath: folder.path) else { return [] }
        var sources: [URL] = []
        while let relativePath = walker.nextObject() as? String {
            if (relativePath as NSString).lastPathComponent.hasPrefix(".") {
                walker.skipDescendants()
                continue
            }
            guard relativePath.hasSuffix(".swift"),
                walker.fileAttributes?[.type] as? FileAttributeType != .typeDirectory,
                !exceptions.contains(where: { relativePath == $0 || relativePath.hasPrefix($0 + "/") })
            else { continue }
            sources.append(folder.appendingPathComponent(relativePath).standardizedFileURL.resolvingSymlinksInPath())
        }
        return sources
    }

    /*
     Where a group or file reference sits on disk, or nil when its source tree is not one this project's sources
     live in. `<group>` is relative to the containing group, and a group with no path adds nothing to the
     chain; the main group, and anything no group contains, resolves against the source root.
     */
    func resolvedLocation(_ identifier: String) throws -> URL? {
        var visited: Set<String> = []
        return try resolvedLocation(identifier, visited: &visited)
    }

    private func resolvedLocation(_ identifier: String, visited: inout Set<String>) throws -> URL? {
        guard visited.insert(identifier).inserted else {
            throw failure("group \(identifier) contains itself")
        }
        let object = try object(identifier, as: "group or file")
        let base: URL
        switch object["sourceTree"] as? String {
            case "<group>":
                guard identifier != mainGroup, let parent = parents[identifier] else {
                    base = sourceRoot
                    break
                }
                guard let parentLocation = try resolvedLocation(parent, visited: &visited) else { return nil }
                base = parentLocation
            case "SOURCE_ROOT":
                base = sourceRoot
            case "<absolute>":
                base = URL(fileURLWithPath: "/", isDirectory: true)
            default:
                return nil
        }
        guard let path = object["path"] as? String, !path.isEmpty else { return base }
        let location =
            path.hasPrefix("/") ? URL(fileURLWithPath: path) : base.appendingPathComponent(path)
        return location.standardizedFileURL
    }

    /*
     Every local package the project links. A package reference's `relativePath` counts from the folder holding the
     .xcodeproj. A file reference counts only when its folder holds a `Package.swift`, since a folder reference is
     also how a project ships a plain directory of resources.
     */
    func localPackages() throws -> [URL] {
        let bundleParent = projectFile.deletingLastPathComponent().deletingLastPathComponent()
        var found = Set<URL>()
        for (identifier, object) in objects {
            let candidate: URL?
            switch object["isa"] as? String {
                case "XCLocalSwiftPackageReference":
                    candidate = (object["relativePath"] as? String).map {
                        $0.hasPrefix("/") ? URL(fileURLWithPath: $0) : bundleParent.appendingPathComponent($0)
                    }
                case "PBXFileReference" where !((object["path"] as? String) ?? "").hasSuffix(".swift"):
                    candidate = try resolvedLocation(identifier)
                default:
                    candidate = nil
            }
            guard let directory = candidate?.standardizedFileURL.resolvingSymlinksInPath(),
                FileManager.default.fileExists(atPath: directory.appendingPathComponent("Package.swift").path)
            else { continue }
            found.insert(directory)
        }
        return found.sorted { $0.path < $1.path }
    }

    /*
     One build setting from a configuration list: the configuration it names as default, else `Debug`, else its
     first. Only the setting written in the project file; an xcconfig's is not read.
     */
    func setting(_ name: String, configurationList: Any?) throws -> String? {
        guard let configurationList else { return nil }
        guard let listIdentifier = configurationList as? String else {
            throw failure("a buildConfigurationList is not an identifier")
        }
        let list = try object(listIdentifier, as: "configuration list")
        let configurations = try identifiers("buildConfigurations", of: list, "configuration list \(listIdentifier)")
            .map { try object($0, as: "configuration of list \(listIdentifier)") }
        let chosenName = list["defaultConfigurationName"] as? String ?? "Debug"
        let chosen = configurations.first { $0["name"] as? String == chosenName } ?? configurations.first
        return (chosen?["buildSettings"] as? [String: Any])?[name] as? String
    }
}
