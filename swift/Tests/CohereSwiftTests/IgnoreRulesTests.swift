            at: GitIndexTests.sharedIndex(version: version),
            to: fixture.root.appendingPathComponent(".git/index"),
        )
        #expect(try fixture.visible() == (tracked + [".gitignore"]).sorted())
        #expect(try fixture.rules().indexFallbackReason == nil)
    }

